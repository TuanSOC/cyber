#!/usr/bin/env python3
"""Run the M6 §14 report metrics and print (optionally write) their table.

Runs the `metric` test `apps/api/tests/reports_metric/test_report_metric.py` in api-test
(REPORT_METRIC=1) and prints the table it reports: citation resolution accuracy, render
success and latency per format, deterministic render rate, hostile escapes, and the
`scripts/verify_report.py` pass and tamper-detection rates, over a synthetic dataset (20
generated cases by default, including the committed hostile snapshot and hostile rows). The
test asserts the floors. Standard library only; run it from the repo root.

Heavy: real renders through `report-worker-test` (about 240 renditions for 20 cases, each
rendered twice for determinism). Start the renderer on the broker db of the lane you use:

  docker compose --profile test up -d report-worker-test                  # default lane
  TEST_BROKER_DB=5 docker compose --profile test up -d report-worker-test # for --lane 5

  python scripts/report_metric.py                    # print the table
  python scripts/report_metric.py --write            # + plans/reports/report-metric-YYMMDD.md
  python scripts/report_metric.py --lane 5 --cases 8 --write
  python scripts/report_metric.py --write --verapdf  # + veraPDF on the golden PDF (not gating)

Options:
  --write [PATH]  write the Markdown report (default plans/reports/report-metric-<YYMMDD>.md,
                  today in UTC); written whether or not the floors are met (status recorded)
  --cases N       cases to generate (default 20, at least 4)
  --lane N        run through scripts/lane-test.sh N (lanes 2..8) instead of the default lane
  --deps          let compose start api-test's dependencies (default lane only)
  --verapdf       validate the golden PDF as PDF/A-3a with a one-off `verapdf/cli` container
                  (recorded as pass / fail / not run; never affects the exit status)
  --verapdf-image IMAGE@sha256:DIGEST
                  the veraPDF image (default: verapdf/cli pinned by digest); must be
                  pinned by an @sha256 digest, a bare tag is refused

Exit status: the test's (non-zero when a floor fails or the table is missing).
"""

import argparse
import datetime as dt
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "plans" / "reports"
OUT_HOST = ROOT / "apps" / "api" / "test-results" / "report-metric"  # gitignored
OUT_CONTAINER = "/srv/api/test-results/report-metric"
BEGIN = "=== REPORT METRIC BEGIN ==="
END = "=== REPORT METRIC END ==="
PYTEST = [
    "uv",
    "run",
    "pytest",
    "-q",
    "-s",
    "-p",
    "no:cacheprovider",
    "-m",
    "metric",
    "tests/reports_metric",
]
# Pinned by digest (Docker Hub `verapdf/cli`, tag v1.30.3 = `latest` on 2026-10-27): never a
# moving tag. `--verapdf-image` overrides it, and must be pinned by digest too.
VERAPDF_IMAGE = (
    "verapdf/cli:v1.30.3@sha256:d74b7026c18a0f171e73c153b617fe6520e1511feb24ca98a348b2bb897669fb"
)
PINNED_IMAGE = re.compile(r"^[a-z0-9][a-z0-9._/:-]*@sha256:[0-9a-f]{64}$")
HEADER = """# M6 report metrics (§14)

Generated {date} by `{command}` (test
`apps/api/tests/reports_metric/test_report_metric.py`, marker `metric`, REPORT_METRIC=1).
Floors: **{status}** (pytest exit {code}).

**Synthetic data.** Every case is generated by `apps/api/tests/reports_metric/harness.py`
(seeded RNG): pcap / static rows, notes, IOC collections, ATT&CK mappings and mock AI runs
are synthetic, and the hostile strings are generated fixtures (plus the committed
`hostile_snapshot.json` / `golden_snapshot.json`), never real evidence. What is real: the
API's finalize, redaction and Ed25519 signing, the broker, the sandboxed `report-worker-test`
renders, the MinIO uploads, the trusted ingest, the downloads and `scripts/verify_report.py`.
Latencies are this host with one renderer replica, and are not a capacity figure. The
escape scanners are standard-library approximations; the authoritative parser checks
(markdown-it, pypdf) are the worker suite. Cases: {cases}; lane: {lane}.

"""


def extract(output: str) -> str | None:
    start = output.find(BEGIN)
    end = output.find(END, start + 1)
    if start < 0 or end < 0:
        return None
    return output[start + len(BEGIN) : end].strip("\n")


def renderer_running() -> bool | None:
    proc = subprocess.run(  # noqa: S603 - a fixed argument list, no shell
        ["docker", "compose", "--profile", "test", "ps", "--status", "running", "--services"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        return None
    return "report-worker-test" in proc.stdout.split()


def verapdf(pdf: Path, image: str = VERAPDF_IMAGE) -> str:
    """PDF/A-3a validation of the golden PDF: `pass`, `fail` or `not run (...)`."""
    if not PINNED_IMAGE.fullmatch(image):
        return "not run (the veraPDF image is not pinned by @sha256 digest)"
    if not pdf.is_file():
        return "not run (no golden PDF was rendered)"
    if shutil.which("docker") is None:
        return "not run (docker not found)"
    proc = subprocess.run(  # noqa: S603 - a fixed argument list, no shell
        [
            "docker",
            "run",
            "--rm",
            "--network",
            "none",
            "-v",
            f"{pdf.parent.resolve()}:/data:ro",
            image,
            "--flavour",
            "3a",
            f"/data/{pdf.name}",
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    output = proc.stdout + proc.stderr
    found = re.search(r'isCompliant="(true|false)"', output)
    if found:
        return "pass" if found.group(1) == "true" else "fail"
    if re.search(r"^PASS\b", output, re.MULTILINE):
        return "pass"
    if re.search(r"^FAIL\b", output, re.MULTILINE):
        return "fail"
    tail = " ".join(output.strip().splitlines()[-2:])[:200]
    return f"not run (veraPDF exit {proc.returncode}: {tail or 'no output'})"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", nargs="?", const="", default=None, metavar="PATH")
    parser.add_argument("--cases", type=int, default=20)
    parser.add_argument("--lane", type=int, default=None)
    parser.add_argument("--deps", action="store_true", help="start api-test's dependencies")
    parser.add_argument("--verapdf", action="store_true", help="run veraPDF (not gating)")
    parser.add_argument(
        "--verapdf-image",
        default=VERAPDF_IMAGE,
        metavar="IMAGE@sha256:DIGEST",
        help="the veraPDF image, pinned by digest (default: the pinned verapdf/cli)",
    )
    args = parser.parse_args()
    if not PINNED_IMAGE.fullmatch(args.verapdf_image):
        parser.error("--verapdf-image must be pinned by digest (name@sha256:<64 hex>)")
    if args.cases < 4:
        parser.error("--cases must be at least 4")
    if args.lane is not None and not 2 <= args.lane <= 8:
        parser.error("--lane must be 2..8")

    if renderer_running() is False:
        sys.stderr.write(
            "report_metric: report-worker-test is not running; start it on the lane's broker "
            "db (see --help), or every render times out\n"
        )
    shutil.rmtree(OUT_HOST, ignore_errors=True)
    inner = [
        "env",
        "REPORT_METRIC=1",
        f"REPORT_METRIC_CASES={args.cases}",
        f"REPORT_METRIC_OUT={OUT_CONTAINER}",
        *PYTEST,
    ]
    if args.lane is not None:
        command = ["bash", "scripts/lane-test.sh", str(args.lane), *inner]
    else:
        command = ["docker", "compose", "--profile", "test", "run", "--rm"]
        if not args.deps:
            command.append("--no-deps")
        command += ["api-test", *inner]
    proc = subprocess.run(  # noqa: S603 - a fixed argument list, no shell
        command,
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    table = extract(proc.stdout)
    if table is None:
        sys.stderr.write(proc.stdout[-4000:] + proc.stderr[-4000:])
        sys.stderr.write("\nreport_metric: the metric table was not printed (see above)\n")
        return proc.returncode or 1
    golden = OUT_HOST / "golden.pdf"
    verapdf_result = verapdf(golden, args.verapdf_image) if args.verapdf else "not run"
    vera = (
        "\n\n## veraPDF (recorded, never gating)\n\n"
        f"- PDF/A-3a validation of the golden PDF (`{args.verapdf_image}`, one-off container, no "
        f"network): **{verapdf_result}**.\n"
    )
    print(table + vera)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout[proc.stdout.find(END) :][-4000:])
        sys.stderr.write(f"\nreport_metric: the metric test failed (exit {proc.returncode})\n")
    if args.write is not None:
        now = dt.datetime.now(dt.UTC)
        path = Path(args.write) if args.write else REPORTS / f"report-metric-{now:%y%m%d}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        flags = [f"--cases {args.cases}", "--write"]
        if args.lane is not None:
            flags.insert(0, f"--lane {args.lane}")
        if args.verapdf:
            flags.append("--verapdf")
            if args.verapdf_image != VERAPDF_IMAGE:
                flags.append(f"--verapdf-image {args.verapdf_image}")
        header = HEADER.format(
            date=now.strftime("%Y-%m-%d %H:%M UTC"),
            command="python scripts/report_metric.py " + " ".join(flags),
            status="met" if proc.returncode == 0 else "NOT met",
            code=proc.returncode,
            cases=args.cases,
            lane="default" if args.lane is None else args.lane,
        )
        path.write_text(header + table + vera, encoding="utf-8", newline="\n")
        shown = path.relative_to(ROOT) if path.is_relative_to(ROOT) else path
        print(f"\nwritten: {shown}")
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
