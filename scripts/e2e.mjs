#!/usr/bin/env node
// `pnpm e2e` (add `--prod` for the prod-like stack over TLS; name filters run only the matching
// specs, e.g. `pnpm e2e reports`): Playwright golden path against
// the running stack. Each run registers a fresh user, so the per-IP register rate limit is
// cleared first; that is the only state this touches besides the data the test itself creates.
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { readFileSync, readdirSync, rmSync } from "node:fs";
import { resolve } from "node:path";

const PROD = process.argv.includes("--prod");
const COMPOSE = PROD ? "docker compose -f docker-compose.yml -f docker-compose.prod.yml" : "docker compose";
// E2E_PROD tells threat-intel.spec.ts and ai-analyst.spec.ts to assert the `mock` providers
// are refused instead of running the enrichment / AI flows against them.
const TARGET = PROD ? "-e E2E_BASE_URL=https://gateway:8443 -e E2E_IGNORE_HTTPS_ERRORS=1 -e E2E_PROD=1" : "";

function sh(command) {
  console.log(`  $ ${command}`);
  const result = spawnSync(command, { shell: true, stdio: "inherit" });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function docker(args) {
  const result = spawnSync("docker", args, { stdio: "inherit" });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

// Synthetic test data lives in a named Docker volume, never on the host disk: host AV
// quarantines the packer-marker sample seconds after it lands there. Leftover host copies
// from older runs (.e2e-data/) are removed first.
rmSync(resolve(".e2e-data"), { recursive: true, force: true });
const VOLUME = "cyberlab_e2e_samples"; // docker-compose.yml `e2e_samples` (external)
docker(["volume", "create", VOLUME]);
// The one-off generators run as root only to write into the fresh volume (nothing runs the
// samples). Clear the previous run's files first.
const asRoot = ["run", "--rm", "--user", "0", "-v", `${VOLUME}:/out`];
docker([...asRoot, "--entrypoint", "sh", "cyberlab/static-worker:dev", "-c", "rm -rf /out/* && mkdir -p /out/static"]);

// Synthetic capture dataset for the PCAP scenario, generated by the worker image (scapy).
// The generator sources are mounted, so a stale image still writes the current dataset.
const datasetSrc = resolve("apps/workers/pcap/dataset");
const pcapGen = [...asRoot, "--entrypoint", "python",
  "-v", `${datasetSrc}:/srv/workers/pcap/dataset:ro`, "cyberlab/pcap-worker:dev"];
docker([...pcapGen, "-m", "dataset.generate", "/out"]);
// A small capture whose names are aimed at the `mock` threat-intel provider (threat-intel
// spec). The run label gives the rate-limited name a fresh first lookup on every run.
docker([...pcapGen, "-m", "dataset.ti_mock", "/out", randomBytes(4).toString("hex")]);
// Two small captures carrying `ai-mock` markers for the AI analyst spec (a 429 once, then a
// verifiable answer; a hostile answer). The run label gives the 429 a fresh first request.
docker([...pcapGen, "-m", "dataset.ai_mock", "/out", randomBytes(4).toString("hex")]);

// Synthetic executables for the static scenarios (they only reference APIs or carry packer
// markers; never executed). Only these files are kept: the full set includes EICAR.
// packed_like.bin gives capa an ATT&CK-mapped capability.
docker([
  ...asRoot, "--entrypoint", "sh", "cyberlab/static-worker:dev",
  "-c", "python -m samples.generate /tmp/samples >/dev/null && cp /tmp/samples/downloader_imports.bin /tmp/samples/packed_like.bin /out/static/ && chmod -R a+rX /out",
]);

// M8 phase 11: the synthetic Linux memory image (LiME) of memory.spec.ts, from the memory
// worker's own generator (stdlib only; the sources are mounted, so a stale image still writes
// the current one). Dev only: its ISF (our own, for a fictional kernel) goes into the stack's
// symbol store through the operator tool (idempotent: `unchanged` on later runs), so the real
// engine resolves it. The prod-like stack's store stays untouched and the spec skips there.
const memgenSrc = resolve("apps/workers/memory/samples");
const memgen = ["run", "--rm", "--user", "0", "-v", `${memgenSrc}:/srv/workers/memory/samples:ro`];
docker([
  ...memgen, "-v", `${VOLUME}:/out`, "--entrypoint", "sh", "cyberlab/memory-worker:dev", "-c",
  "mkdir -p /out/memory && python -m samples.memgen --scenario linux_benign --format lime --out /out/memory/synthetic.lime && chmod -R a+rX /out/memory",
]);
if (!PROD) {
  docker([
    ...memgen, "-v", `${resolve(".memory-import")}:/out`, "--entrypoint", "python", "cyberlab/memory-worker:dev",
    "-m", "samples.memgen", "--isf-out", "/out/cyberlab-synthetic-6.1.0.json.xz",
  ]);
  sh(`${COMPOSE} --profile tools run --rm memory-symbols-init`);
  sh("node scripts/memory-symbols.mjs import --file cyberlab-synthetic-6.1.0.json.xz");
}

// Dev: the `mock` providers' sinks (their keys reach the e2e container through compose
// interpolation, never through this script's output). Prod has no sink: the specs assert
// the mocks are refused there. ai-mock is recreated so it forgets the markers it has seen.
if (!PROD) sh(`${COMPOSE} --profile e2e up -d --wait --no-deps --force-recreate ti-mock ai-mock`);

// M7 phase 11: the purged-evidence state of retention.spec.ts, dev only (the prod overlay's api
// env makes the seeder refuse: ENV=prod, secure cookies). A one-off container of the dev `api`
// service (app/scripts/e2e_seed.py) registers a seed user with its own org, a case and a text
// upload through the API, then writes as the owner a completed retention run, the purge
// tombstone and the custody `purged` event. The seed password is generated here and passed to
// both containers through the environment only (`-e NAME` without a value): it is never part
// of a printed command or of any output.
function envFileValue(name) {
  if (process.env[name]) return process.env[name];
  const line = readFileSync(resolve(".env"), "utf8")
    .split(/\r?\n/)
    .find((l) => l.startsWith(`${name}=`));
  return line ? line.slice(name.length + 1) : "";
}

function seedPurgedEvidence() {
  if (PROD) {
    console.log("  (prod: no purged-evidence seed; retention.spec.ts skips its seeded steps)");
    return "";
  }
  const ownerUrl = envFileValue("MIGRATION_DATABASE_URL");
  if (!ownerUrl) {
    console.error("e2e seed: MIGRATION_DATABASE_URL is not set in .env");
    process.exit(1);
  }
  process.env.E2E_SEED_PASSWORD = randomBytes(18).toString("base64url");
  const args = [
    "compose", "run", "--rm", "--no-deps", "-T",
    "-e", "CYBERLAB_E2E_SEED=1", "-e", "E2E_SEED_PASSWORD", "-e", "E2E_OWNER_DATABASE_URL",
    "api", "uv", "run", "python", "-m", "app.scripts.e2e_seed",
  ];
  console.log(`  $ docker ${args.join(" ")}`);
  const result = spawnSync("docker", args, {
    env: { ...process.env, E2E_OWNER_DATABASE_URL: ownerUrl, MSYS_NO_PATHCONV: "1" },
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });
  if (result.status !== 0) process.exit(result.status ?? 1);
  const seed = JSON.parse(result.stdout.trim().split(/\r?\n/).pop());
  process.env.E2E_SEED_EMAIL = seed.email;
  process.env.E2E_SEED_PURGED_EVIDENCE = `${seed.org_id}/${seed.evidence_id}`;
  console.log(`  e2e seed: ${seed.email}, purged evidence ${process.env.E2E_SEED_PURGED_EVIDENCE}`);
  return "-e E2E_SEED_EMAIL -e E2E_SEED_PASSWORD -e E2E_SEED_PURGED_EVIDENCE";
}
const SEED = seedPurgedEvidence();

// Every spec registers one fresh user, and registration is limited to 5 per 10 minutes per IP:
// the specs run in batches of at most five, with the register keys cleared before each.
// A Lua one-liner avoids shell pipes, so it behaves the same under cmd.exe and sh.
function clearRegisterLimit() {
  sh(
    `${COMPOSE} exec -T redis redis-cli EVAL "for _,k in ipairs(redis.call('KEYS', ARGV[1])) do redis.call('DEL', k) end return 1" 0 "rl:register:*"`,
  );
}
// Optional name filters (`pnpm e2e reports`): only the specs whose file name contains one.
const filters = process.argv.slice(2).filter((arg) => !arg.startsWith("--"));
const specs = readdirSync(resolve("apps/web/e2e"))
  .filter((name) => name.endsWith(".spec.ts"))
  .filter((name) => !filters.length || filters.some((f) => name.includes(f)))
  .sort();
if (!specs.length) {
  console.error(`no e2e spec matches ${filters.join(", ")}`);
  process.exit(1);
}
const BATCH = 5;
for (let i = 0; i < specs.length; i += BATCH) {
  clearRegisterLimit();
  const files = specs.slice(i, i + BATCH).map((name) => `e2e/${name}`).join(" ");
  sh(`${COMPOSE} --profile e2e run --rm ${i === 0 ? "--build" : ""} ${TARGET} ${SEED} e2e pnpm exec playwright test ${files}`);
}
