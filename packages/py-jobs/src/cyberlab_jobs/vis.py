"""Make invisible characters visible: `⟨U+202E⟩` (M6, RT24).

The code points come from `vis_rules.json`, a materialized range list generated by
`scripts/gen_vis_rules.py` from the M5 `ai/text.py` categories under Python 3.12
`unicodedata` (C0 / C1 controls except `\\n` and `\\t`, DEL, bidi overrides and isolates,
zero-width characters, tag characters and every other `Cf` character, plus variation
selectors, Hangul fillers, U+034F and the line / paragraph separators). No runtime
"category Cf" check happens here or in the web viewer (`apps/web/lib/vis-rules.json` is a
byte-identical copy), so the renderer and the browser cannot drift apart.

The snapshot holds the defanged text already; renderers and the viewer apply only `vis`.
"""

import bisect
import json
from functools import lru_cache
from importlib import resources
from typing import Any

VIS_RULES_FILE = "vis_rules.json"


@lru_cache(maxsize=1)
def rules() -> dict[str, Any]:
    raw = resources.files("cyberlab_jobs").joinpath(VIS_RULES_FILE).read_text(encoding="utf-8")
    data: dict[str, Any] = json.loads(raw)
    return data


@lru_cache(maxsize=1)
def _table() -> tuple[list[int], list[int]]:
    starts: list[int] = []
    ends: list[int] = []
    for start, end, _category in rules()["ranges"]:
        starts.append(int(start))
        ends.append(int(end))
    return starts, ends


def is_invisible(cp: int) -> bool:
    starts, ends = _table()
    i = bisect.bisect_right(starts, cp) - 1
    return i >= 0 and cp <= ends[i]


def marker(cp: int) -> str:
    return f"⟨U+{cp:04X}⟩"


def vis(text: str) -> str:
    """Every listed code point replaced by its visible marker; everything else unchanged."""
    if text.isascii() and text.isprintable():
        return text
    return "".join(marker(ord(ch)) if is_invisible(ord(ch)) else ch for ch in text)
