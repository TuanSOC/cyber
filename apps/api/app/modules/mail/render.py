"""Mail plain-text rendering and email message assembly (M11 phase 2).

All email generated by CyberLab is strictly plain text (decision):
- No HTML, no multipart/alternative, no tracking pixels, no remote stylesheets/images.
- Fixed subjects defined in `app.modules.mail.templates.SUBJECTS`.
- Links are ASCII-safe and place the secret in the URL fragment (`#t=<token>`),
  preventing leakage via HTTP referrers or logs.
- Bodies are capped at 8 KiB (8192 bytes).
- CR/LF and Unicode bidi control characters are refused with `RenderRefusedError`.
- Organization names and user names are quoted; link-like names (`://`, `www.`,
  or dotted host-like tokens) are replaced with neutral labels to prevent phishing (RT20).
"""

from __future__ import annotations

import email.policy
import email.utils
from email.message import EmailMessage
import re
from typing import Any
from urllib.parse import urlparse

from pydantic import ValidationError

from app.modules.mail.templates import (
    LINK_PATHS,
    SUBJECTS,
    ApiKeyCreatedParams,
    InviteParams,
    MailTemplate,
    RecoveryCodeUsedParams,
    SecurityChangeParams,
    SsoLinkedParams,
    UserParams,
)

MAX_BODY_BYTES = 8192

# Unicode bidirectional control characters
BIDI_CONTROLS = frozenset({
    "\u061C",  # ALM
    "\u200E",  # LRM
    "\u200F",  # RLM
    "\u202A",  # LRE
    "\u202B",  # RLE
    "\u202C",  # PDF
    "\u202D",  # LRO
    "\u202E",  # RLO
    "\u2066",  # LRI
    "\u2067",  # RLI
    "\u2068",  # FSI
    "\u2069",  # PDI
})

# Matches link-like strings: scheme ://, www. prefix, or host-like patterns with dots
_LINK_LIKE = re.compile(
    r"://|www\.|\b[a-zA-Z0-9](?:[a-zA-Z0-9-]*[a-zA-Z0-9])?\.[a-zA-Z]{2,}\b"
)


class RenderRefusedError(ValueError):
    """Refused rendering due to security violations, size caps, or invalid parameters."""


def _check_string_safety(val: str) -> None:
    if "\r" in val or "\n" in val:
        raise RenderRefusedError("CR or LF characters not permitted in parameters")
    for char in val:
        if char in BIDI_CONTROLS:
            raise RenderRefusedError(f"bidi control character {ord(char):04X} not permitted")


def _check_params_safety(val: Any) -> None:
    if isinstance(val, str):
        _check_string_safety(val)
    elif isinstance(val, dict):
        for k, v in val.items():
            _check_params_safety(k)
            _check_params_safety(v)
    elif isinstance(val, (list, tuple, set, frozenset)):
        for item in val:
            _check_params_safety(item)


def _sanitize_org_name(name: str) -> str:
    _check_string_safety(name)
    if _LINK_LIKE.search(name):
        return "an organization on CyberLab"
    return f'"{name}"'


def _sanitize_name(name: str) -> str:
    _check_string_safety(name)
    if _LINK_LIKE.search(name):
        return "a user on CyberLab"
    return f'"{name}"'


def _build_link(public_base_url: str, path: str, token: str) -> str:
    _check_string_safety(token)
    base = public_base_url.rstrip("/")
    link = f"{base}{path}#t={token}"
    try:
        link.encode("ascii")
    except UnicodeEncodeError as exc:
        raise RenderRefusedError("link URL must be ASCII-safe") from exc
    return link


def render_template_body(
    template: MailTemplate,
    params: dict[str, Any],
    *,
    token: str | None = None,
    public_base_url: str = "http://localhost:8080",
) -> str:
    """Render plain-text body for the given template."""
    _check_params_safety(params)
    link_path = LINK_PATHS.get(template)
    link = _build_link(public_base_url, link_path, token) if link_path and token else None

    try:
        body = _render_body_inner(template, params, link=link)
    except ValidationError as exc:
        raise RenderRefusedError(f"invalid parameter: {exc}") from exc

    return body


def _render_body_inner(
    template: MailTemplate,
    params: dict[str, Any],
    *,
    link: str | None = None,
) -> str:
    if template == MailTemplate.INVITE:
        parsed_invite = InviteParams.model_validate(params)
        org = _sanitize_org_name(parsed_invite.org_name)
        inviter = _sanitize_name(parsed_invite.inviter_name)
        expires = parsed_invite.expires_at.strftime("%Y-%m-%d %H:%M:%S UTC")
        if not link:
            raise RenderRefusedError("invite template requires token link")
        body = (
            f"You have been invited by {inviter} to join {org} on CyberLab "
            f"as {parsed_invite.role.value}.\n\n"
            f"To accept this invitation, open the following link in your browser:\n"
            f"{link}\n\n"
            f"This invitation link expires on {expires}.\n"
            f"If you did not expect this invitation, you can safely ignore this email.\n"
        )

    elif template == MailTemplate.EMAIL_VERIFY:
        parsed_user = UserParams.model_validate(params)
        user = _sanitize_name(parsed_user.display_name)
        if not link:
            raise RenderRefusedError("email_verify template requires token link")
        body = (
            f"Hello {user},\n\n"
            f"Please verify your email address for your CyberLab account by opening this link:\n"
            f"{link}\n\n"
            f"If you did not register for CyberLab, you can safely ignore this email.\n"
        )

    elif template == MailTemplate.PASSWORD_RESET:
        parsed_user = UserParams.model_validate(params)
        user = _sanitize_name(parsed_user.display_name)
        if not link:
            raise RenderRefusedError("password_reset template requires token link")
        body = (
            f"Hello {user},\n\n"
            f"A password reset was requested for your CyberLab account. "
            f"You can set a new password by opening this link:\n"
            f"{link}\n\n"
            f"If you did not request a password reset, you can safely ignore this email.\n"
        )

    elif template == MailTemplate.PASSWORD_CHANGED:
        parsed_user = UserParams.model_validate(params)
        user = _sanitize_name(parsed_user.display_name)
        body = (
            f"Hello {user},\n\n"
            f"The password for your CyberLab account was recently changed.\n\n"
            f"If you made this change, no further action is needed.\n"
            f"If you did not make this change, please contact your organization administrator immediately.\n"
        )

    elif template == MailTemplate.MFA_ENABLED:
        parsed_user = UserParams.model_validate(params)
        user = _sanitize_name(parsed_user.display_name)
        body = (
            f"Hello {user},\n\n"
            f"Two-factor authentication (TOTP) has been enabled on your CyberLab account.\n\n"
            f"If you did not enable two-factor authentication, please contact your administrator immediately.\n"
        )

    elif template == MailTemplate.MFA_DISABLED:
        parsed_user = UserParams.model_validate(params)
        user = _sanitize_name(parsed_user.display_name)
        body = (
            f"Hello {user},\n\n"
            f"Two-factor authentication (TOTP) has been disabled on your CyberLab account.\n\n"
            f"If you did not disable two-factor authentication, please contact your administrator immediately.\n"
        )

    elif template == MailTemplate.MFA_LOCKED:
        parsed_user = UserParams.model_validate(params)
        user = _sanitize_name(parsed_user.display_name)
        body = (
            f"Hello {user},\n\n"
            f"Your CyberLab account has been locked due to multiple failed two-factor authentication attempts.\n\n"
            f"Please use one of your recovery codes to sign in, or contact your organization administrator for assistance.\n"
        )

    elif template == MailTemplate.RECOVERY_CODE_USED:
        parsed_rec = RecoveryCodeUsedParams.model_validate(params)
        user = _sanitize_name(parsed_rec.display_name)
        body = (
            f"Hello {user},\n\n"
            f"A recovery code was used to sign in to your CyberLab account.\n\n"
            f"Remaining recovery codes: {parsed_rec.remaining}.\n"
            f"If you did not use a recovery code, please reset your password and two-factor authentication immediately.\n"
        )

    elif template == MailTemplate.MFA_RESET_BY_OPERATOR:
        parsed_user = UserParams.model_validate(params)
        user = _sanitize_name(parsed_user.display_name)
        body = (
            f"Hello {user},\n\n"
            f"Your two-factor authentication settings have been reset by an administrator.\n\n"
            f"You will be prompted to set up two-factor authentication the next time you sign in.\n"
        )

    elif template == MailTemplate.SSO_ACCOUNT_LINKED:
        parsed_sso = SsoLinkedParams.model_validate(params)
        user = _sanitize_name(parsed_sso.display_name)
        org = _sanitize_org_name(parsed_sso.org_name)
        _check_string_safety(parsed_sso.issuer_host)
        body = (
            f"Hello {user},\n\n"
            f"Your CyberLab account was linked to single sign-on (SSO) with {org} via {parsed_sso.issuer_host}.\n\n"
            f"If you did not authorize this change, please contact your organization administrator.\n"
        )

    elif template == MailTemplate.API_KEY_CREATED:
        parsed_key = ApiKeyCreatedParams.model_validate(params)
        org = _sanitize_org_name(parsed_key.org_name)
        key_name = _sanitize_name(parsed_key.key_name)
        creator = _sanitize_name(parsed_key.creator_name)
        expires = parsed_key.expires_at.strftime("%Y-%m-%d %H:%M:%S UTC")
        body = (
            f"A new API key {key_name} was created for {org} with role {parsed_key.role} by {creator}.\n\n"
            f"Expires on: {expires}.\n"
        )

    elif template == MailTemplate.NEW_OWNER_SECURITY_CHANGE:
        parsed_sec = SecurityChangeParams.model_validate(params)
        org = _sanitize_org_name(parsed_sec.org_name)
        actor = _sanitize_name(parsed_sec.actor_name)
        _check_string_safety(parsed_sec.change)
        body = (
            f"Security settings for {org} were updated by {actor}.\n\n"
            f"Change type: {parsed_sec.change}.\n"
        )

    else:
        raise RenderRefusedError(f"unknown template: {template}")

    return body


def render_mail(
    template_str: str,
    params: dict[str, Any],
    *,
    token: str | None = None,
    to_email: str,
    from_email: str,
    public_base_url: str = "http://localhost:8080",
) -> EmailMessage:
    """Render plain-text mail and construct an EmailMessage object."""
    template = MailTemplate(template_str)
    subject = SUBJECTS.get(template)
    if not subject:
        raise RenderRefusedError(f"no subject for template {template}")

    _check_string_safety(subject)
    _check_string_safety(to_email)
    _check_string_safety(from_email)

    body = render_template_body(
        template,
        params,
        token=token,
        public_base_url=public_base_url,
    )

    parsed = urlparse(public_base_url)
    domain = parsed.hostname or "localhost"

    msg = EmailMessage(policy=email.policy.SMTP)
    msg["From"] = from_email
    msg["To"] = to_email
    msg["Subject"] = subject
    msg["Date"] = email.utils.formatdate(localtime=False)
    msg["Message-ID"] = email.utils.make_msgid(domain=domain)
    msg["Auto-Submitted"] = "auto-generated"
    msg.set_content(body)

    return msg
