"""`FakeProvider`: rule-based, deterministic, in-process (M5 phase 1, FROZEN behaviour).

Used by CI, worker and API tests and by the eval harness as the honest baseline. It reads the
in-process `ProviderRequest.context` (never the rendered prompt, so it does not depend on the
phase-5 prompt format) and produces a schema-valid `AnalysisOutput` dict:
- `observed`: one claim per top item (kind priority J/M -> F -> A/S/C -> I/T -> E -> N/R,
  then context order), up to `MAX_OBSERVED_CLAIMS`, each citing the item's first quotable
  field with an exact quote of it (≤ 120 characters) and anchored to that quote (the claim
  text contains it);
- `interpretation`: one claim citing the first item (field, no quote);
- `attack_techniques`: every T-id carried by capability items (their `attack_ids` /
  `attack` fields), cited with that field;
- `timeline`: one entry per timeline item (summaries and incidents only);
- one hypothesis, one next step (refs = the first label), one limitation.
Usage is chars/4. `D` (digest) items are never cited as evidence.
"""

import json
import re
from typing import Any

from app.modules.ai.contracts import (
    AiTask,
    ContextItem,
    FrozenContext,
    ProviderRequest,
    ProviderResult,
    ProviderUsage,
    RefKind,
    VerifyOutcome,
    VerifyStatus,
)

MAX_OBSERVED_CLAIMS = 5
MAX_QUOTE_CHARS = 120
_PRIORITY = {
    RefKind.JOB: 0,
    RefKind.SAMPLE: 0,
    RefKind.INVESTIGATION: 0,
    RefKind.FINDING: 1,
    RefKind.ALERT: 2,
    RefKind.SIGNATURE: 2,
    RefKind.CAPABILITY: 2,
    RefKind.PE_SUMMARY: 2,
    RefKind.IOC: 3,
    RefKind.TI_RESULT: 3,
    RefKind.TIMELINE: 4,
    RefKind.EVIDENCE: 4,
    RefKind.FLOW: 5,
    RefKind.RECORD: 5,
    RefKind.STRING: 6,
}
_ATTACK_ID = re.compile(r"\bT\d{4}(?:\.\d{3})?\b")
_ALNUM = re.compile(r"[A-Za-z0-9]")
_TIMELINE_TASKS = frozenset({AiTask.SUMMARIZE_PCAP, AiTask.INCIDENT_SUMMARY, AiTask.JOB_DIGEST})


def _quotable(item: ContextItem) -> tuple[str, str] | None:
    """The first field whose value is a string of ≥ 8 characters with an alphanumeric."""
    for name in sorted(item.fields):
        value = item.fields[name]
        if isinstance(value, str) and len(value) >= 8 and _ALNUM.search(value):
            return name, value[:MAX_QUOTE_CHARS]
    return None


def _evidence(ctx: FrozenContext) -> list[ContextItem]:
    items = [i for i in ctx.items if i.kind is not RefKind.DIGEST_CLAIM]
    order = {id(item): n for n, item in enumerate(items)}
    return sorted(items, key=lambda i: (_PRIORITY.get(i.kind, 9), order[id(i)]))


def fake_output(ctx: FrozenContext | None, task: AiTask | None = None) -> dict[str, Any]:
    """The deterministic output for a context (also used directly by tests)."""
    limitation = "Generated by the rule-based test provider: no model judgement involved."
    if ctx is None or not ctx.items:
        return {
            "overall_confidence": {"level": "low", "rationale": "No evidence was provided."},
            "limitations": [limitation, "The context was empty."],
        }
    task = task or ctx.task
    evidence = _evidence(ctx)
    observed: list[dict[str, Any]] = []
    for item in evidence:
        if len(observed) >= MAX_OBSERVED_CLAIMS:
            break
        quotable = _quotable(item)
        if quotable is None:
            continue
        field, quote = quotable
        observed.append(
            {
                "id": f"O{len(observed) + 1}",
                "text": f"{item.label} {field}: {quote}"[:600],
                "confidence": "high",
                "citations": [{"ref": item.label, "field": field, "quote": quote}],
            }
        )
    first = evidence[0] if evidence else ctx.items[0]
    first_field = sorted(first.fields)[0] if first.fields else None
    interpretation = [
        {
            "id": "I1",
            "text": f"The selected evidence centres on {first.label}.",
            "confidence": "medium",
            "citations": [{"ref": first.label, "field": first_field}],
        }
    ]
    techniques: list[dict[str, Any]] = []
    seen: set[str] = set()
    for item in evidence:
        if item.kind is not RefKind.CAPABILITY:
            continue
        for field in ("attack_ids", "attack"):
            value = item.fields.get(field)
            if not isinstance(value, str):
                continue
            for tid in _ATTACK_ID.findall(value):
                if tid in seen or len(techniques) >= 20:
                    continue
                seen.add(tid)
                techniques.append(
                    {
                        "technique_id": tid,
                        "rationale": f"Capability {item.label} maps to {tid}.",
                        "citations": [{"ref": item.label, "field": field, "quote": tid}],
                    }
                )
    timeline: list[dict[str, Any]] = []
    if task in _TIMELINE_TASKS:
        for item in evidence:
            if item.kind is RefKind.TIMELINE and len(timeline) < 60:
                timeline.append(
                    {
                        "text": f"Event {item.label}.",
                        "citations": [{"ref": item.label, "field": sorted(item.fields)[0]}]
                        if item.fields
                        else [{"ref": item.label}],
                    }
                )
    output: dict[str, Any] = {
        "observed": observed,
        "interpretation": interpretation,
        "hypotheses": [
            {
                "id": "H1",
                "text": "The observed activity may warrant a closer look by an analyst.",
                "confidence": "low",
                "supporting": [{"ref": first.label}],
                "contradicting": [],
            }
        ],
        "overall_confidence": {
            "level": "medium",
            "rationale": "Deterministic summary of the highest-priority evidence items.",
        },
        "next_steps": [
            {
                "text": f"Review {first.label} and its related records.",
                "rationale": "It is the highest-priority item in the context.",
                "refs": [first.label],
            }
        ],
        "limitations": [limitation],
        "attack_techniques": techniques,
        "timeline": timeline,
    }
    return output


class FakeProvider:
    """Implements `contracts.LlmProvider`. `calls` counts `analyze` invocations."""

    name = "fake"

    def __init__(self, model: str = "fake-1") -> None:
        self.model = model
        self.calls = 0

    async def analyze(self, request: ProviderRequest) -> ProviderResult:
        self.calls += 1
        output = fake_output(request.context)
        sent = len(request.system) + len(request.user)
        usage = ProviderUsage(input_tokens=sent // 4, output_tokens=len(json.dumps(output)) // 4)
        return ProviderResult(
            parsed=output, usage=usage, served_model=request.model, stop_reason="end_turn"
        )

    async def count_tokens(self, request: ProviderRequest) -> int | None:
        return (len(request.system) + len(request.user)) // 4

    async def verify(self) -> VerifyOutcome:
        return VerifyOutcome(status=VerifyStatus.VALID)

    async def aclose(self) -> None:
        return None
