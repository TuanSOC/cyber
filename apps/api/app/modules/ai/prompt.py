"""Prompt rendering (signatures FROZEN in phase 1; phase 5 fills the bodies and owns
`PROMPT_VERSION`, which it bumps on any template change).

`render` returns the system prompt (stable, cacheable) and the user turn: the task enum,
kind/count stats and the evidence JSON between `<<EVIDENCE {delimiter}>>` lines. Nothing
analyzer-, user- or TI-controlled appears outside that block (RT4).

Layout (decided in phase 5):
- `system` = `prompts/common.txt`, byte-identical for every run of a prompt version, so the
  provider's prompt cache (Anthropic `cache_control` on the system block) hits across runs,
  tasks and orgs. It holds no per-request value.
- `user` = `prompts/user_head.txt` (task statement from `prompts/<task>.txt`, the context
  stats, the per-request canary instruction, the spotlighting note), the evidence block, then
  `prompts/user_tail.txt` (the reminder that the block was data). The canary lives in the user
  turn, after any cache breakpoint, because a per-request value in the system prompt would
  defeat the cache.
- Outside the block the user turn contains only template text, `AiTask` / `RefKind` values,
  integers, one label (the explain target), the canary and the delimiter (both generated by
  the worker and pattern-checked here).

The evidence is the canonical JSON array of the context items (sorted keys, no whitespace,
NFC, non-ASCII kept), i.e. the `items` of `FrozenContext.canonical_json()`.
"""

import hashlib
import json
import re
import unicodedata
from functools import lru_cache
from pathlib import Path
from string import Template

from app.modules.ai.contracts import AiTask, ContextStats, FrozenContext, PromptParts, RefKind
from app.modules.ai.labels import is_label

PROMPT_VERSION = "m5.1"

PROMPTS_DIR = Path(__file__).resolve().parent / "prompts"
DELIMITER_PATTERN = re.compile(r"[0-9a-f]{32}")
CANARY_PATTERN = re.compile(r"[A-Za-z0-9_-]{16,128}")
MAX_REPAIR_ERRORS = 12
MAX_REPAIR_PATH = 96

# The explain tasks name their target: the first item of this kind in the context (the
# builder puts the target first, so it is F1 / A1, or J{n}:F1 in a reduce).
_TARGET_KIND = {AiTask.EXPLAIN_FINDING: RefKind.FINDING, AiTask.EXPLAIN_ALERT: RefKind.ALERT}

# Fixed phrases of the stats section (part of the pinned prompt; see `templates_sha256`).
STATS_PHRASES = {
    "included": "- Items included per kind (included of available): {parts}.",
    "none": "- No evidence items were included.",
    "omitted": "- Items omitted to stay within the limits: {n}.",
    "truncated": "- Field values cut to the length limit: {n} ({parts}).",
    "dropped_keys": "- Attribute keys dropped because their names were not valid: {n}.",
    "pseudonymized": "- Internal values replaced by pseudonyms: {parts}.",
    "neutralized": "- Pseudonym-like tokens found in raw text and neutralized: {n}.",
    "stripped": "- Invisible or control characters removed from the evidence: {n}.",
    "jobs_omitted": "- Jobs of this incident left out over the job limit: {n}.",
    "pseudonym_note": (
        "- Tokens such as INT_IP_3, INT_HOST_1 or USER_2 are pseudonyms for internal values "
        "that were replaced before sending."
    ),
}
# Only these category names may appear outside the block (the dicts are builder-written).
_PSEUDONYM_KINDS = ("ip", "host", "user")
_TEMPLATE_FILES = (
    "common.txt",
    "user_head.txt",
    "user_tail.txt",
    *(f"{task.value}.txt" for task in AiTask),
)


def _read(name: str) -> str:
    # LF-normalized: the pinned hashes must not depend on a checkout's line endings.
    return (PROMPTS_DIR / name).read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n")


@lru_cache(maxsize=1)
def _templates() -> dict[str, str]:
    return {name: _read(name) for name in _TEMPLATE_FILES}


def templates_sha256() -> dict[str, str]:
    """sha256 per template file plus `stats` for the fixed stats phrases; a test pins these
    to `PROMPT_VERSION`."""
    digests = {
        name: hashlib.sha256(text.encode()).hexdigest() for name, text in _templates().items()
    }
    phrases = json.dumps(STATS_PHRASES, sort_keys=True, ensure_ascii=False)
    digests["stats"] = hashlib.sha256(phrases.encode()).hexdigest()
    return digests


def system_prompt() -> str:
    return _templates()["common.txt"]


def evidence_json(ctx: FrozenContext) -> str:
    """The canonical JSON array of the items, exactly as placed inside the block."""
    items = [item.model_dump(mode="json") for item in ctx.items]
    text = json.dumps(items, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return unicodedata.normalize("NFC", text)


def _target_label(ctx: FrozenContext, task: AiTask) -> str | None:
    kind = _TARGET_KIND.get(task)
    if kind is None:
        return None
    label = next((i.label for i in ctx.items if i.kind is kind), None)
    return label if label is not None and is_label(label) else None


def _task_statement(ctx: FrozenContext, task: AiTask) -> str:
    template = Template(_templates()[f"{task.value}.txt"])
    target = _target_label(ctx, task)
    return template.substitute(target=target or "(not included in the evidence)")


def _render_stats(stats: ContextStats) -> str:
    lines: list[str] = []
    included = [
        f"{kind.value} {stats.per_kind[kind].included} of {stats.per_kind[kind].total}"
        for kind in RefKind
        if kind in stats.per_kind
    ]
    if included:
        lines.append(STATS_PHRASES["included"].format(parts=", ".join(included)))
    else:
        lines.append(STATS_PHRASES["none"])
    if stats.omitted:
        lines.append(STATS_PHRASES["omitted"].format(n=int(stats.omitted)))
    truncated = [
        f"{kind.value} {int(stats.truncated_fields[kind])}"
        for kind in RefKind
        if stats.truncated_fields.get(kind)
    ]
    total_truncated = sum(int(n) for n in stats.truncated_fields.values())
    if total_truncated:
        lines.append(
            STATS_PHRASES["truncated"].format(n=total_truncated, parts=", ".join(truncated))
        )
    if stats.dropped_keys:
        lines.append(STATS_PHRASES["dropped_keys"].format(n=int(stats.dropped_keys)))
    # Keys are builder-written, but only the fixed category names ever reach the prompt.
    pseudonyms = [
        f"{name} {int(stats.pseudonymized.get(name, 0))}"
        for name in _PSEUDONYM_KINDS
        if stats.pseudonymized.get(name)
    ]
    if pseudonyms:
        lines.append(STATS_PHRASES["pseudonymized"].format(parts=", ".join(pseudonyms)))
    if stats.neutralized:
        lines.append(STATS_PHRASES["neutralized"].format(n=int(stats.neutralized)))
    stripped = sum(int(n) for n in stats.stripped.values() if isinstance(n, int))
    if stripped:
        lines.append(STATS_PHRASES["stripped"].format(n=stripped))
    if stats.jobs_omitted:
        lines.append(STATS_PHRASES["jobs_omitted"].format(n=int(stats.jobs_omitted)))
    lines.append(STATS_PHRASES["pseudonym_note"])
    return "\n".join(lines)


def render(ctx: FrozenContext, task: AiTask, *, delimiter: str, canary: str) -> PromptParts:
    """Deterministic for a fixed context, task, delimiter and canary.

    Raises `ValueError` when the delimiter is not 32 lowercase hex characters, when the
    canary is not 16-128 URL-safe characters, or when either occurs inside the evidence
    JSON (the worker then regenerates them)."""
    if not DELIMITER_PATTERN.fullmatch(delimiter):
        raise ValueError("delimiter must be 32 lowercase hex characters")
    if not CANARY_PATTERN.fullmatch(canary):
        raise ValueError("canary must be 16-128 URL-safe characters")
    evidence = evidence_json(ctx)
    if delimiter in evidence:
        raise ValueError("delimiter_collision")
    if canary.lower() in evidence.lower():
        raise ValueError("canary_collision")
    templates = _templates()
    head = Template(templates["user_head.txt"]).substitute(
        task=_task_statement(ctx, task),
        stats=_render_stats(ctx.stats),
        canary=canary,
        delimiter=delimiter,
    )
    user = "\n".join(
        (
            head,
            f"<<EVIDENCE {delimiter}>>",
            evidence,
            f"<<END EVIDENCE {delimiter}>>",
            templates["user_tail.txt"],
        )
    )
    return PromptParts(system=system_prompt(), user=user, delimiter=delimiter, canary=canary)


_SAFE_PATH = re.compile(r"[^A-Za-z0-9_.\[\]]")


def repair_hint(errors: list[str]) -> str:
    """A short fixed text naming the schema violations (paths only, never values).

    `errors` are `ValidationFailed.errors` (`path: error_type`); anything outside
    `[A-Za-z0-9_.[]]` is replaced, each entry is cut, and at most `MAX_REPAIR_ERRORS` are
    listed."""
    entries: list[str] = []
    for raw in errors[:MAX_REPAIR_ERRORS]:
        path, _, kind = str(raw).partition(":")
        path = _SAFE_PATH.sub("?", path.strip())[:MAX_REPAIR_PATH] or "(root)"
        kind = _SAFE_PATH.sub("?", kind.strip())[:48]
        entries.append(f"- {path}: {kind}" if kind else f"- {path}")
    more = len(errors) - len(entries)
    if more > 0:
        entries.append(f"- and {more} more")
    listing = "\n".join(entries) if entries else "- (the answer was not a JSON object)"
    return (
        "Your previous answer did not match the required response schema. Problems at:\n"
        f"{listing}\n"
        "Answer again with one JSON object that matches the schema exactly, with no other text."
    )
