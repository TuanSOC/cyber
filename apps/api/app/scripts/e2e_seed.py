"""Seed the purged-evidence state of `apps/web/e2e/retention.spec.ts` (M7 phase 11, dev only).

`scripts/e2e.mjs` runs it as a one-off container of the dev `api` service (`docker compose run
--rm --no-deps -T api uv run python -m app.scripts.e2e_seed`) against the running dev stack:

- through the real API (`E2E_API_URL`, default `http://api:8000`): registers a seed user (its
  own organization), a case and one small text evidence upload (no analyzer takes text);
- as the owner (`E2E_OWNER_DATABASE_URL`, `app.org_id` set): a completed enforce retention
  run labelled `e2e`, the evidence's purge tombstone and its custody `purged` event by the
  retention system user. The object version stays in MinIO (dev data; `reconcile_orphans.py`
  reports it as `purged_pending_delete`).

The seed password comes in `E2E_SEED_PASSWORD` (generated by e2e.mjs, which hands it to the e2e
container through the environment only). stdout: one JSON line `{"email", "org_id",
"evidence_id"}`; the password is never printed or logged.

Guard (exit 1 before any request or write): `CYBERLAB_E2E_SEED=1`, and the compose model's
dev api env: `ENV=dev` set explicitly (an unset ENV is refused, though the settings default to
dev) and read back through `get_settings()`, secure cookies off (the prod overlay sets
`ENV=prod` and secure cookies). The target must be the dev stack too: `E2E_API_URL` is plain
http on the compose network or loopback, the owner URL names this api's own database (host,
port and name of `DATABASE_URL`), and the API must serve `/api/docs` (only an `ENV=dev` api
does) before the seed user is registered. This writes as the owner and fabricates a purge:
never on a prod stack.
"""

import asyncio
import hashlib
import json
import os
import secrets
import sys
from collections.abc import Mapping
from typing import Any

import httpx
from sqlalchemy import text
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

from app.core.config import RETENTION_SYSTEM_USER_ID, Settings, get_settings
from app.scripts.drill_seed import DrillError, Session

API = "/api/v1"
LABEL = json.dumps({"label": "e2e"})
MIN_PASSWORD = 12
DEFAULT_API_URL = "http://api:8000"
# The dev compose network's service names, or loopback (a dev api published on the host).
DEV_API_HOSTS = frozenset({"api", "localhost", "127.0.0.1", "::1"})
DEV_DB_HOSTS = frozenset({"postgres", "localhost", "127.0.0.1", "::1"})


class SeedError(Exception):
    pass


def _dev_api_url(url: str) -> str:
    parts = httpx.URL(url)
    if parts.scheme != "http" or parts.host not in DEV_API_HOSTS:
        raise SeedError("refusing to run: E2E_API_URL is not the dev api (http on api/loopback)")
    return url


def _same_database(owner_url: str, api_url: str) -> None:
    """The owner URL must name this api's own database (and a dev database host)."""
    try:
        owner, api = make_url(owner_url), make_url(api_url)
    except Exception as exc:  # noqa: BLE001 - never echo a URL (it carries a password)
        raise SeedError("refusing to run: a database URL does not parse") from exc
    same = (owner.host, owner.port or 5432, owner.database) == (
        api.host,
        api.port or 5432,
        api.database,
    )
    if owner.host not in DEV_DB_HOSTS or not same:
        raise SeedError("refusing to run: E2E_OWNER_DATABASE_URL is not the dev api's database")


def require_dev(env: Mapping[str, str] | None = None, settings: Settings | None = None) -> str:
    """The seed password, or SeedError unless this is the dev e2e's one-off seed container."""
    env = os.environ if env is None else env
    if env.get("CYBERLAB_E2E_SEED") != "1":
        raise SeedError("refusing to run: CYBERLAB_E2E_SEED=1 is not set (pnpm e2e only)")
    # Explicitly dev: an unset ENV would read as the settings' default (dev).
    if env.get("ENV") != "dev":
        raise SeedError("refusing to run: ENV=dev is not set (the e2e seed is dev only)")
    if settings is None:
        try:
            settings = get_settings()
        except Exception as exc:  # noqa: BLE001 - a settings error names no secret here
            raise SeedError("refusing to run: the api settings do not load") from exc
    if settings.env != "dev":
        raise SeedError("refusing to run: the api settings are not ENV=dev")
    if settings.cookie_secure or env.get("COOKIE_SECURE", "false").lower() in ("1", "true", "yes"):
        raise SeedError("refusing to run: COOKIE_SECURE is on (a prod-like api env)")
    owner_url = env.get("E2E_OWNER_DATABASE_URL")
    if not owner_url:
        raise SeedError("E2E_OWNER_DATABASE_URL is not set")
    _same_database(owner_url, settings.database_url)
    _dev_api_url(env.get("E2E_API_URL", DEFAULT_API_URL))
    password = env.get("E2E_SEED_PASSWORD", "")
    if len(password) < MIN_PASSWORD:
        raise SeedError(f"E2E_SEED_PASSWORD must have at least {MIN_PASSWORD} characters")
    return password


def require_dev_api(client: httpx.Client) -> None:
    """The target api runs ENV=dev: only then does it serve the interactive docs."""
    try:
        response = client.get("/api/docs")
    except httpx.HTTPError as exc:
        raise SeedError("refusing to run: the api did not answer /api/docs") from exc
    if response.status_code != 200:
        raise SeedError("refusing to run: the api is not ENV=dev (/api/docs is not served)")


def _seed_api(password: str) -> dict[str, Any]:
    tag = secrets.token_hex(4)
    email = f"e2e-seed-{tag}@example.com"
    url = _dev_api_url(os.environ.get("E2E_API_URL", DEFAULT_API_URL))
    client = httpx.Client(base_url=url, timeout=60)
    with client:
        require_dev_api(client)
        user = Session(client)
        body = user.json(
            "POST",
            f"{API}/auth/register",
            201,
            json={
                "email": email,
                "password": password,
                "display_name": "E2E Seed Viewer",
                "organization_name": f"E2E Seed Org {tag}",
            },
        )
        org = body["memberships"][0]["organization_id"]
        case = user.json(
            "POST",
            f"{API}/orgs/{org}/investigations",
            201,
            json={"title": "E2E purged evidence", "severity": "low"},
        )["id"]
        data = f"cyberlab e2e purged evidence {tag}\n".encode()
        evidence = user.json(
            "POST",
            f"{API}/orgs/{org}/investigations/{case}/evidence",
            201,
            params={"filename": "e2e-purged.txt", "description": "e2e retention seed"},
            content=data,
            headers={"Content-Type": "application/octet-stream"},
        )
    sha = hashlib.sha256(data).hexdigest()
    if evidence.get("hashes", {}).get("sha256") != sha:
        raise SeedError("upload: the API reported another sha256")
    return {
        "email": email,
        "user_id": body["user"]["id"],
        "org_id": org,
        "evidence_id": evidence["id"],
        "sha256": sha,
    }


async def _tombstone(seed: Mapping[str, str], owner_url: str) -> None:
    """The retention run, the purge tombstone and the custody `purged` event (as the owner)."""
    engine = create_async_engine(owner_url, poolclass=NullPool, hide_parameters=True)
    run_id = secrets.token_hex(16)
    try:
        async with engine.begin() as conn:
            await conn.execute(
                text(
                    "SELECT set_config('app.org_id', :o, true), set_config('app.user_id', :u, true)"
                ),
                {"o": seed["org_id"], "u": seed["user_id"]},
            )
            version = (
                await conn.execute(
                    text("SELECT storage_version_id FROM evidence WHERE id = :e"),
                    {"e": seed["evidence_id"]},
                )
            ).scalar_one()
            await conn.execute(
                text(
                    "INSERT INTO retention_runs (id, organization_id, mode, trigger, status, "
                    "policy, counts, started_at, finished_at) VALUES (CAST(:id AS uuid), :org, "
                    "'enforce', 'schedule', 'completed', CAST(:label AS jsonb), "
                    "CAST(:label AS jsonb), now(), now())"
                ),
                {"id": run_id, "org": seed["org_id"], "label": LABEL},
            )
            await conn.execute(
                text(
                    "INSERT INTO evidence_purges (evidence_id, organization_id, run_id, "
                    "object_version_id, sha256) VALUES (:e, :org, CAST(:run AS uuid), :v, :sha)"
                ),
                {
                    "e": seed["evidence_id"],
                    "org": seed["org_id"],
                    "run": run_id,
                    "v": version,
                    "sha": seed["sha256"],
                },
            )
            await conn.execute(
                text(
                    "INSERT INTO evidence_custody_events (organization_id, evidence_id, action, "
                    "actor_id, details) VALUES (:org, :e, 'purged', :actor, "
                    "CAST(:details AS jsonb))"
                ),
                {
                    "org": seed["org_id"],
                    "e": seed["evidence_id"],
                    "actor": str(RETENTION_SYSTEM_USER_ID),
                    "details": json.dumps({"run_id": run_id, "version_id": version}),
                },
            )
    finally:
        await engine.dispose()


def seed(env: Mapping[str, str] | None = None) -> dict[str, str]:
    env = os.environ if env is None else env
    password = require_dev(env)
    data = _seed_api(password)
    asyncio.run(_tombstone(data, env["E2E_OWNER_DATABASE_URL"]))
    return {"email": data["email"], "org_id": data["org_id"], "evidence_id": data["evidence_id"]}


def main() -> int:
    try:
        out = seed()
    except (SeedError, DrillError) as exc:
        print(f"e2e_seed: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
