"""Harness for the M6 §14 report metrics (phase 9): citation resolution, render success and
latency, deterministic renders, hostile escapes and offline verification.

Everything here is **synthetic**: the cases, their analysis rows, notes, collections, AI runs
and hostile strings are generated by this module (seeded RNG, `SEED`), never real evidence.
The renders are real: the API finalizes and signs for real, publishes `report.render` on the
lane's broker, and `report-worker-test` (sandboxed WeasyPrint / Jinja2 / Markdown) renders,
uploads to `reports-test` and answers `report.rendered`, which this process ingests.

Cases (`build_plan`, default 20):
- `fixture_golden` / `fixture_hostile`: the committed golden and hostile snapshots
  (`tests/fixtures/report/`), stored and signed with `seed_version` (no finalize, so no
  citation measurement; their ids are rewritten to the seeded report's);
- `hostile_rows` (n // 10): a case whose pcap rows (findings, alerts, IOCs, DNS records,
  timeline), notes, sections, title, AI claim and distribution carry `HOSTILE_VALUES`, all
  cited; inputs the API refuses are recorded as refused (blocked at input), not as escapes;
- `dataset` (the rest): the pcap sample rows plus 0-40 generated rows, an optional static
  job, notes, an IOC collection, a confirmed ATT&CK technique and a mock AI run, with 1-8
  cited rows drawn by the RNG.

Each finalized case gets v1 `internal` and v2 `external` (distribution + review ack). Every
version is rendered as PDF (queued at finalize), HTML and Markdown through the API.

Measurements:
- **citation resolution accuracy**: right after finalize, every `report_citations` row is
  re-resolved (`citations.resolve`, the requester's tenant session and case scope) and must
  give the same table and `fields_sha256`; its snapshot item (same `cite_no`) must name the
  same row and hash to its `fields_sha256` (internal: the same hash as the row; external:
  the redacted copy's own hash). Also recorded: selected rows present in the snapshot and
  `dropped_out_of_scope` (expected 0 on this dataset);
- **render success** per format and group (non-hostile / hostile; a hostile failure must be
  a typed `error_code`), **latency** from the request (or the finalize response for the
  finalize PDF) to the `report.rendered` message (harness polls every `POLL_S`), the DB's
  `created_at -> finished_at`, and finalize wall time (snapshot build + sign + store);
- **deterministic render rate**: each succeeded rendition is rendered again by a twin
  render row of the same version (inserted here, bypassing the API's dedupe, published with
  `dispatch.publish`). Its artifact is read from MinIO and compared byte for byte; the twin
  is then closed through the trusted ingest as `failed / renderer_error` so it frees its
  slot (bookkeeping only: twins are not counted in the success rate or latency);
- **hostile escapes** (floor 0), scanned on every artifact with the standard library only
  (api-test has no markdown-it or pypdf; the authoritative parser checks are the worker
  suite): HTML outside the template's tag / attribute allow-list, links outside `#...` and
  `PUBLIC_BASE_URL`, CSS from data, comments, a head other than `HTML_HEAD`, raw bidi /
  zero-width / tag characters; Markdown links, images, raw HTML, entities, autolinks and
  linkify targets (URLs, `www.`, e-mail) outside code spans and backslash escapes, table
  cells starting a formula (`=`, `+`, `@`); PDF `/URI` actions outside `PUBLIC_BASE_URL` and
  any JavaScript / Launch / SubmitForm / ImportData / GoToR / RichMedia name in an object
  dictionary or object stream (embedded files and page content are not scanned);
- **verify_report.py**: the downloaded PDF and the snapshot + `.sig.json` must verify
  (exit 0); five tampered variants must be refused (exit 1): a flipped byte of the embedded
  snapshot, an appended incremental update, a flipped snapshot byte, a flipped signature
  character, and a wrong pinned key under the same kid.

Not measured here: peak render RSS (the worker's `test_render_budget.py`), PDF text
extraction of `⟨U+202E⟩` (the worker's `test_render_pdf.py`), worker fetch logs, viewer-vs-PDF
parity, veraPDF (the host wrapper `scripts/report_metric.py --verapdf`, never gating).
"""

