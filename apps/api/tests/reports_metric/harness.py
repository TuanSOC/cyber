class Runner:
    def __init__(
        self, keys: SigningKeys, work: Path, script: Path, cases: int = DEFAULT_CASES
    ) -> None:
        self.keys = keys
        self.work = work
        self.script = script
        self.metric = Metric(plan=build_plan(cases))
        self.seen: dict[uuid.UUID, tuple[dict[str, Any], float]] = {}
        self.twins: set[uuid.UUID] = set()
        self.keys_file = work / "keys.json"
        self.keys_file.write_text(json.dumps({keys.kid: keys.public_b64}), encoding="utf-8")
        self.wrong_keys = work / "wrong-keys.json"
        other = new_signing_keys(keys.kid)
        self.wrong_keys.write_text(json.dumps({keys.kid: other.public_b64}), encoding="utf-8")

    async def run(self) -> Metric:
        started = time.perf_counter()
        for plan in self.metric.plan:
            try:
                if plan.fixture:
                    await self._fixture_case(plan)
                else:
                    await self._finalized_case(plan)
            except Exception as exc:  # noqa: BLE001 - recorded; a floor fails on any error
                tb = traceback.format_exception_only(type(exc), exc)[-1].strip()
                self.metric.case_errors.append(f"case {plan.index} ({plan.kind}): {tb[:300]}")
        self.metric.runtime_s = time.perf_counter() - started
        return self.metric

    # --- API helpers ---

    async def _post(
        self, ctx: _Case, path: str, body: dict[str, Any], what: str | None = None
    ) -> dict[str, Any] | None:
        """POST under the org; a 4xx is fatal unless `what` names a lenient (hostile) input."""
        response = await ctx.reg.client.post(
            f"{API}/{ctx.reg.org_id}{path}", json=body, headers=csrf(ctx.reg.client)
        )
        if response.status_code in (200, 201, 202):
            data: dict[str, Any] = response.json()
            return data
        if what is not None and 400 <= response.status_code < 500:
            self._refused(ctx, what, response)
            return None
        raise AssertionError(f"POST {path}: {response.status_code} {response.text[:300]}")

    def _refused(self, ctx: _Case, what: str, response: Response) -> None:
        code = ""
        try:
            code = str(response.json().get("code") or "")
        except ValueError:
            pass
        self.metric.refused_inputs.append(
            f"case {ctx.plan.index}: {what} -> {response.status_code} {code}".rstrip()
        )

    async def _get(self, ctx: _Case, url: str) -> Response:
        response = await ctx.reg.client.get(url)
        if response.status_code != 200:
            raise AssertionError(f"GET {url}: {response.status_code} {response.text[:300]}")
        return response

    # --- cases ---

    async def _fixture_case(self, plan: CasePlan) -> None:
        name = "golden" if plan.kind == "fixture_golden" else "hostile"
        reg, t = await owner_case(org_name=f"Metric org {plan.index}", title=f"Metric {name}")
        ctx = _Case(plan, reg, t)
        base = parse_snapshot((FIXTURES / f"{name}_snapshot.json").read_bytes())
        tlp, profile = str(base.report.tlp), str(base.report.profile)
        report_id = await seed_report(t, title=f"Metric fixture {name}", tlp=tlp, profile=profile)
        info = base.report.model_copy(update={"report_id": report_id, "version": 1})
        snapshot = base.model_copy(update={"report": info})
        seeded = await seed_version(
            t, report_id, self.keys, snapshot=snapshot, tlp=tlp, profile=profile
        )
        version = _Version(seeded.version_id, report_id, 1, profile, base.report.base_url)
        sample = VersionSample(plan.index, plan.kind, profile)
        self.metric.versions.append(sample)
        await self._render_all(ctx, version, sample, pdf=None)

    async def _finalized_case(self, plan: CasePlan) -> None:
        rng = random.Random(f"{SEED}:case:{plan.index}")  # noqa: S311 - synthetic dataset
        hostile = plan.kind == "hostile_rows"
        reg, t = await owner_case(
            org_name=f"Metric org {plan.index}", title=f"Metric case {plan.index}"
        )
        ctx = _Case(plan, reg, t)
        case = f"/investigations/{t.investigation_id}"
        if hostile:
            extra = hostile_records(plan.index)
        else:
            extra = benign_records(plan.index, plan.extra_rows, rng)
        _, job = await pcap_job(reg, t, [*pcap_results.sample_records(), *extra])
        if plan.static:
            await static_job(reg, t)

        candidates: list[tuple[str, str]] = []
        for kind, model in (
            ("finding", AnalysisFinding),
            ("alert", NetworkAlert),
            ("ioc", Ioc),
            ("record", NetworkRecord),
        ):
            candidates += [(kind, str(row.id)) for row in await rows_of(t, model, job)]
        if hostile:
            selected = candidates[:150]
        else:
            selected = rng.sample(candidates, min(plan.cited, len(candidates)))

        note_ids: list[str] = []
        for n in range(plan.notes):
            body = "\n\n".join(HOSTILE_VALUES) if hostile else f"Synthetic note {n}: beacon review."
            payload = {"body": body, "include_in_reports": True}
            note = await self._post(ctx, f"{case}/notes", payload, "note body" if hostile else None)
            if note is None:
                payload["body"] = "Hostile note refused at input."
                note = await self._post(ctx, f"{case}/notes", payload)
            assert note is not None
            note_ids.append(str(note["id"]))

        collections: list[str] = []
        if plan.collection_items:
            path = f"{case}/ioc-collections"
            if hostile:
                name = "<script>alert(8)</script> list \u202e"
                coll = await self._post(ctx, path, {"name": name}, "collection name")
            else:
                coll = await self._post(ctx, path, {"name": f"Metric blocklist {plan.index}"})
            if coll is None:
                coll = await self._post(ctx, path, {"name": "Metric blocklist"})
            assert coll is not None
            items = [
                {"type": "domain", "value": f"c2-{k}.case{plan.index}.example"}
                for k in range(plan.collection_items)
            ]
            await self._post(ctx, f"/ioc-collections/{coll['id']}/items", {"items": items})
            collections.append(str(coll["id"]))

        if plan.attack:
            technique = {"technique_id": "T1071.001", "status": "confirmed"}
            await self._post(ctx, f"{case}/attack", technique)

        ai_runs: list[str] = []
        if plan.ai_run:
            findings = await rows_of(t, AnalysisFinding, job)
            claim = "Periodic connections"
            if hostile:
                claim = f"{HOSTILE_VALUES[0]} {HOSTILE_VALUES[17]}"
            cited = [("finding", str(findings[0].id))]
            ai_runs.append(str(await ai_run_on(t, job, claims=[("o1", claim, cited)])))

        if hostile:
            sections = {
                "executive_summary": "\n".join(HOSTILE_VALUES),
                "recommendations": HOSTILE_VALUES[1],
            }
        else:
            summary = f"Synthetic case {plan.index}: beaconing to one destination."
            sections = {"executive_summary": summary}
        plain_title = f"Metric report {plan.index}"
        created = await api_create(reg, t, title=HOSTILE_TITLE if hostile else plain_title)
        if created.status_code != 201 and hostile:
            self._refused(ctx, "report title", created)
            created = await api_create(reg, t, title=plain_title)
        assert created.status_code == 201, created.text
        report_id = uuid.UUID(created.json()["id"])
        draft: dict[str, Any] = {
            "sections": sections,
            "include": {
                "iocs": {"case_iocs": plan.case_iocs, "collections": collections},
                "notes": note_ids,
                "ai_runs": ai_runs,
                "cited_rows": [{"kind": k, "ref_id": r} for k, r in selected],
            },
        }
        patched = await api_patch(reg, report_id, draft=draft)
        if patched.status_code != 200 and hostile:
            self._refused(ctx, "draft sections", patched)
            draft["sections"] = {"executive_summary": "Hostile sections refused at input."}
            patched = await api_patch(reg, report_id, draft=draft)
        assert patched.status_code == 200, patched.text

        await self._finalize(ctx, report_id, "internal", selected, {})
        distribution = HOSTILE_DISTRIBUTION if hostile else DISTRIBUTION
        patched = await api_patch(reg, report_id, profile="external", distribution=distribution)
        if patched.status_code != 200 and hostile:
            self._refused(ctx, "distribution", patched)
            patched = await api_patch(reg, report_id, profile="external", distribution=DISTRIBUTION)
        assert patched.status_code == 200, patched.text
        ack = {"acknowledge_external_review": True}
        await self._finalize(ctx, report_id, "external", selected, ack)

    async def _finalize(
        self,
        ctx: _Case,
        report_id: uuid.UUID,
        profile: str,
        selected: list[tuple[str, str]],
        extra: dict[str, Any],
    ) -> None:
        started = time.monotonic()
        response = await api_finalize(ctx.reg, report_id, change_note=f"Metric {profile}", **extra)
        finalize_s = time.monotonic() - started
        assert response.status_code == 201, response.text
        rendered_from = time.monotonic()  # the PDF was published before the response
        body = response.json()
        sample = VersionSample(ctx.plan.index, ctx.plan.kind, profile, finalize_s=finalize_s)
        self.metric.versions.append(sample)
        url = f"{API}/{ctx.reg.org_id}/reports/{report_id}/versions/{body['version']}"
        snapshot = parse_snapshot((await self._get(ctx, f"{url}/content")).content)
        number = int(body["version"])
        version_id = uuid.UUID(body["id"])
        version = _Version(version_id, report_id, number, profile, snapshot.report.base_url)
        await self._citations(ctx, version, snapshot, sample, selected)
        renders = (await self._get(ctx, f"{url}/renders")).json()["items"]
        pdf = [r for r in renders if r["format"] == "pdf"]
        assert len(pdf) == 1, renders
        queued = (uuid.UUID(pdf[0]["id"]), rendered_from)
        await self._render_all(ctx, version, sample, pdf=queued)

    # --- citations ---

    async def _citations(
        self,
        ctx: _Case,
        version: _Version,
        snapshot: ReportSnapshot,
        sample: VersionSample,
        selected: list[tuple[str, str]],
    ) -> None:
        t = ctx.t
        async with tenant_session(t.org_id, t.owner_id) as session:
            rows = list(
                await session.scalars(
                    select(ReportCitation)
                    .where(ReportCitation.version_id == version.id)
                    .order_by(ReportCitation.cite_no)
                )
            )
            case = await session.get(Investigation, t.investigation_id)
            assert case is not None
            scope = await cites.CaseScope.load(session, t.org_id, case)
            requests = [
                cites.CiteRequest(
                    r.kind, r.ref_id, r.job_id, r.source, r.ai_citation_id, r.ref_table
                )
                for r in rows
            ]
            resolved = await cites.resolve(session, scope, requests, with_paths=False)
        items = {c.cite_no: c for c in snapshot.citations.items}
        sample.citations = max(len(rows), len(items))
        for row in rows:
            hit = resolved.get(cites.cite_key(row.kind, row.ref_id, row.job_id))
            equal = (
                hit is not None
                and hit.ref_table == row.ref_table
                and hit.fields_sha256 == row.fields_sha256
            )
            item = items.get(row.cite_no)
            same_row = (row.kind, row.ref_table, row.ref_id)
            consistent = (
                item is not None
                and (item.kind, item.ref_table, item.ref_id) == same_row
                and cites.fields_sha256(item.fields) == item.fields_sha256
                and (version.profile == "external" or item.fields_sha256 == row.fields_sha256)
            )
            sample.resolved_equal += equal
            sample.consistent += consistent
            sample.accurate += equal and consistent
        present = {(c.kind, c.ref_id) for c in snapshot.citations.items}
        sample.selected = len(selected)
        sample.covered = sum(key in present for key in selected)
        sample.dropped = snapshot.citations.dropped_out_of_scope

    # --- renders ---

    async def _render_all(
        self,
        ctx: _Case,
        version: _Version,
        sample: VersionSample,
        pdf: tuple[uuid.UUID, float] | None,
    ) -> None:
        for fmt in FORMATS:
            if fmt == "pdf" and pdf is not None:
                render_id, started = pdf
            else:
                started = time.monotonic()
                path = f"/reports/{version.report_id}/versions/{version.number}/renders"
                queued = await self._post(ctx, path, {"format": fmt})
                assert queued is not None
                render_id = uuid.UUID(queued["id"])
            data = await self._measure(ctx, version, fmt, render_id, started)
            if fmt == "pdf" and data is not None:
                await self._verify(ctx, version, data, sample)
                if ctx.plan.kind == "fixture_golden":
                    self.metric.golden_pdf = data

    async def _measure(
        self, ctx: _Case, version: _Version, fmt: str, render_id: uuid.UUID, started: float
    ) -> bytes | None:
        plan = ctx.plan
        sample = RenderSample(plan.index, plan.kind, version.profile, fmt, plan.hostile)
        self.metric.renders.append(sample)
        got = await self._wait(render_id)
        body = (await self._get(ctx, f"{API}/{ctx.reg.org_id}/report-renders/{render_id}")).json()
        sample.status, sample.error_code = str(body["status"]), body.get("error_code")
        if got is None:
            sample.status = f"no_message ({sample.status})"
            return None
        sample.latency_s = got[1] - started
        if sample.status != "succeeded":
            return None
        if body.get("created_at") and body.get("finished_at"):
            created = datetime.fromisoformat(str(body["created_at"]))
            finished = datetime.fromisoformat(str(body["finished_at"]))
            sample.db_latency_s = (finished - created).total_seconds()
        download = f"{API}/{ctx.reg.org_id}/report-renders/{render_id}/download"
        response = await ctx.reg.client.get(download)
        data = response.content
        if response.status_code != 200 or hashlib.sha256(data).hexdigest() != body.get("sha256"):
            sample.status = f"download_failed ({response.status_code})"
            return None
        sample.size = len(data)
        sample.escapes = scan(fmt, data, version.base_url)
        if plan.hostile:
            sample.payload_visible = payload_visible(fmt, data)
        sample.deterministic = await self._twin_identical(ctx, version, fmt, data)
        return data

    async def _wait(self, render_id: uuid.UUID) -> tuple[dict[str, Any], float] | None:
        deadline = time.monotonic() + RENDER_WAIT_S
        while render_id not in self.seen and time.monotonic() < deadline:
            for message in drain_ingest(POLL_S):
                await self._take(message)
        return self.seen.get(render_id)

    async def _take(self, message: dict[str, Any]) -> None:
        if message.get("schema_version") != RENDERED_SCHEMA:
            self.metric.ignored_messages += 1
            return
        try:
            render_id = uuid.UUID(str(message["render_id"]))
        except (KeyError, ValueError):
            self.metric.ignored_messages += 1
            return
        self.seen[render_id] = (message, time.monotonic())
        if render_id not in self.twins:
            await render_ingest.handle_rendered_message(message)

    async def _twin_identical(self, ctx: _Case, version: _Version, fmt: str, data: bytes) -> bool:
        """Render the same version and format again (a twin row) and compare the bytes."""
        twin_id = await self._create_twin(ctx.t, version, fmt)
        got = await self._wait(twin_id)
        try:
            if got is None or got[0].get("status") != "succeeded":
                return False
            key = dispatch.render_key(ctx.t.org_id, version.report_id, version.number, twin_id, fmt)
            twin = await asyncio.to_thread(_read_object, key, str(got[0]["object_version_id"]))
            return twin == data
        finally:
            renderer = str(got[0].get("renderer_version") or "") if got else ""
            await render_ingest.handle_rendered(
                ReportRenderedV1(
                    render_id=twin_id,
                    token=dispatch.render_token(twin_id),
                    status="failed",
                    error_code=TWIN_CLOSE_CODE,
                    renderer_version=renderer or "report-metric/twin",
                )
            )

    async def _create_twin(self, t: Tenant, version: _Version, fmt: str) -> uuid.UUID:
        render_id = uuid.uuid4()
        self.twins.add(render_id)
        deadline = datetime.now(UTC) + timedelta(seconds=get_settings().report_render_deadline_s)
        async with tenant_session(t.org_id, t.owner_id) as session:
            row = await session.get(ReportVersion, version.id)
            assert row is not None
            render = ReportRender(
                id=render_id,
                organization_id=t.org_id,
                version_id=version.id,
                format=fmt,
                status="queued",
                token_sha256=dispatch.token_sha256(dispatch.render_token(render_id)),
                requested_by=t.owner_id,
            )
            session.add(render)
            await session.flush()
            session.add(
                ReportRenderIndex(
                    render_id=render_id,
                    organization_id=t.org_id,
                    status="queued",
                    dispatched_at=None,
                    deadline_at=deadline,
                    attempts=0,
                )
            )
            await session.flush()
            await session.refresh(render)
            item = dispatch.input_for(render, row, deadline)
        if not await dispatch.publish(item):
            raise AssertionError(f"twin render {render_id}: publish failed")
        return render_id

    # --- offline verification ---

    def _verify_exit(self, *args: str | Path, keys: Path | None = None) -> int:
        command = [sys.executable, str(self.script), *map(str, args)]
        command += ["--keys", str(keys or self.keys_file), "--quiet"]
        return subprocess.run(command, capture_output=True, text=True, check=False).returncode

    async def _verify(
        self, ctx: _Case, version: _Version, pdf: bytes, sample: VersionSample
    ) -> None:
        url = version.path(ctx.reg.org_id)
        snapshot = (await self._get(ctx, f"{url}/content")).content
        sig = (await self._get(ctx, f"{url}/signature")).content
        d = self.work / f"v-{version.id}"
        d.mkdir(parents=True, exist_ok=True)
        files = {
            "good.pdf": pdf,
            "snapshot.json": snapshot,
            "sig.json": sig,
            "incremental.pdf": pdf + _INCREMENTAL,
            "snapshot-flipped.json": _flip_report_id(snapshot),
            "sig-flipped.json": _flip_signature(sig),
        }
        try:
            files["pdf-flipped.pdf"] = _flip_embedded_snapshot(pdf, snapshot)
        except (AssertionError, ValueError):
            # No embedded snapshot equal to the signed bytes: the variant cannot be built,
            # recorded as not detected (pdf_valid fails as well).
            sample.verify["tamper_pdf_embedded_snapshot_byte"] = False
        for name, content in files.items():
            (d / name).write_bytes(content)

        def run(*args: str | Path, keys: Path | None = None) -> int:
            return self._verify_exit(*args, keys=keys)

        snap, sig_file = d / "snapshot.json", d / "sig.json"
        checks: dict[str, tuple[tuple[str | Path, ...], Path | None, int]] = {
            "pdf_valid": (("--pdf", d / "good.pdf"), None, 0),
            "snapshot_valid": (("--snapshot", snap, "--sig", sig_file), None, 0),
            "tamper_pdf_incremental_update": (("--pdf", d / "incremental.pdf"), None, 1),
            "tamper_snapshot_byte": (
                ("--snapshot", d / "snapshot-flipped.json", "--sig", sig_file),
                None,
                1,
            ),
            "tamper_signature_char": (
                ("--snapshot", snap, "--sig", d / "sig-flipped.json"),
                None,
                1,
            ),
            "tamper_wrong_pinned_key": (("--pdf", d / "good.pdf"), self.wrong_keys, 1),
        }
        if "pdf-flipped.pdf" in files:
            flipped: tuple[tuple[str | Path, ...], Path | None, int] = (
                ("--pdf", d / "pdf-flipped.pdf"),
                None,
                1,
            )
            checks["tamper_pdf_embedded_snapshot_byte"] = flipped
        for name, (args, keys, expected) in checks.items():
            sample.verify[name] = await asyncio.to_thread(run, *args, keys=keys) == expected


def _flip_report_id(snapshot: bytes) -> bytes:
    """One hex digit of the report id changed: still valid JSON, a different hash."""
    marker = b'"report_id":"'
    at = snapshot.index(marker) + len(marker)
    tampered = bytearray(snapshot)
    tampered[at] = ord("1") if tampered[at] != ord("1") else ord("2")
    return bytes(tampered)


def _flip_signature(sig: bytes) -> bytes:
    data = json.loads(sig)
    value = str(data["signature"])
    data["signature"] = ("B" if value[:1] == "A" else "A") + value[1:]
    return json.dumps(data).encode("utf-8")
