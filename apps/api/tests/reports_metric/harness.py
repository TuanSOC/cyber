_MD_LINK = re.compile(r"\[([^\]\n]*)\]\(([^)\s]*)")
_MD_REF = re.compile(r"^\s{0,3}\[[^\]\n]+\]:")
_MD_HTML = re.compile(r"<[A-Za-z/!?]")
_MD_ENTITY = re.compile(r"&(#\d+|#[xX][0-9a-fA-F]+|[A-Za-z][A-Za-z0-9]*);")
_MD_SCHEME = re.compile(r"(?i)\b(?:https?|ftp|javascript|data|file|mailto):")
_MD_WWW = re.compile(r"(?i)\bwww\.")
_MD_EMAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+")
_PDF_OBJ = re.compile(rb"(\d+\s+\d+\s+obj\b)(.*?)(\bendobj)", re.DOTALL)
_PDF_STREAM = re.compile(rb">>\s*stream(?:\r\n|\n|\r)")
_PDF_NAME = re.compile(rb"/([^\s/<>\[\]()%{}]*)")
_PDF_HEX = re.compile(rb"#([0-9A-Fa-f]{2})")
