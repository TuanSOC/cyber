def percentile(values: Sequence[float], p: float) -> float | None:
    """Nearest-rank percentile."""
    if not values:
        return None
    ordered = sorted(values)
    return ordered[max(0, math.ceil(p / 100 * len(ordered)) - 1)]


def _rate(num: int, den: int) -> str:
    return f"{num}/{den} = {num / den:.3f}" if den else "n/a (0 samples)"


def _secs(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.2f}"


@dataclass(frozen=True)
class Floor:
    name: str
    ok: bool
    detail: str


def _every(name: str, num: int, den: int, *, empty_ok: bool = False) -> Floor:
    """A rate floor of 1.0 (an empty sample fails unless `empty_ok`)."""
    return Floor(name, num == den and (den > 0 or empty_ok), _rate(num, den))


def floors(metric: Metric) -> list[Floor]:
    finalized = [v for v in metric.versions if v.finalize_s is not None]
    total = sum(v.citations for v in finalized)
    accurate = sum(v.accurate for v in finalized)
    errors = len(metric.case_errors)
    out = [
        Floor("no case setup errors", errors == 0, str(errors)),
        _every("citation resolution accuracy = 1.0", accurate, total),
    ]
    for fmt in FORMATS:
        rs = [r for r in metric.renders if r.fmt == fmt]
        plain = [r for r in rs if not r.hostile]
        ok = sum(r.status == "succeeded" for r in plain)
        out.append(_every(f"{fmt} render success (non-hostile) = 1.0", ok, len(plain)))
        hostile = [r for r in rs if r.hostile]
        typed = sum(r.typed for r in hostile)
        out.append(_every(f"{fmt} hostile renders end typed", typed, len(hostile), empty_ok=True))
        twins = [r for r in rs if r.deterministic is not None]
        same = sum(bool(r.deterministic) for r in twins)
        out.append(_every(f"{fmt} deterministic render rate = 1.0", same, len(twins)))
    escapes = sum(len(r.escapes) for r in metric.renders)
    out.append(Floor("hostile escapes = 0", escapes == 0, str(escapes)))
    checks = [(k, ok) for v in metric.versions for k, ok in v.verify.items()]
    valid = [ok for k, ok in checks if not k.startswith("tamper")]
    out.append(_every("verify_report.py pass rate = 1.0", sum(valid), len(valid)))
    tamper = [ok for k, ok in checks if k.startswith("tamper")]
    out.append(_every("tamper detection rate = 1.0", sum(tamper), len(tamper)))
    return out


def render_table(metric: Metric) -> str:
    """The report body (Markdown). Every number comes from the synthetic dataset above."""
    lines: list[str] = []
    kinds = Counter(p.kind for p in metric.plan)
    finalized = [v for v in metric.versions if v.finalize_s is not None]
    lines += [
        "## Dataset (synthetic)",
        "",
        f"- Cases: {len(metric.plan)} ({', '.join(f'{k} {n}' for k, n in sorted(kinds.items()))}); "
        f"seed {SEED}. All rows, notes, collections, AI runs and hostile strings are generated "
        "by `tests/reports_metric/harness.py`; no real evidence.",
        f"- Finalized versions: {len(finalized)} (v1 internal + v2 external per finalized case); "
        f"seeded fixture versions: {len(metric.versions) - len(finalized)}.",
        f"- Renders measured: {len(metric.renders)} (plus one twin per succeeded rendition for "
        "determinism, not counted below).",
        "- Inputs refused by the API (blocked at input, not escapes): "
        f"{len(metric.refused_inputs)}.",
        f"- Non-report ingest messages ignored: {metric.ignored_messages}.",
        f"- Real runtime: {metric.runtime_s:.0f} s.",
        "",
        "## Floors",
        "",
        "| Metric | Measured | Floor met |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {f.name} | {f.detail} | {'yes' if f.ok else '**NO**'} |" for f in floors(metric)]

    total = sum(v.citations for v in finalized)
    lines += [
        "",
        "## Citations (finalized versions, measured right after finalize)",
        "",
        "| Profile | Versions | Citations | Re-resolved, equal hash | Snapshot item verified | "
        "Accurate | Selected rows in snapshot | Dropped out of scope |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for profile in ("internal", "external"):
        vs = [v for v in finalized if v.profile == profile]
        n = sum(v.citations for v in vs)
        lines.append(
            f"| {profile} | {len(vs)} | {n} | {_rate(sum(v.resolved_equal for v in vs), n)} | "
            f"{_rate(sum(v.consistent for v in vs), n)} | "
            f"{_rate(sum(v.accurate for v in vs), n)} | "
            f"{_rate(sum(v.covered for v in vs), sum(v.selected for v in vs))} | "
            f"{sum(v.dropped for v in vs)} |"
        )
    all_accurate = _rate(sum(v.accurate for v in finalized), total)
    lines.append(f"| all | {len(finalized)} | {total} | | | {all_accurate} | | |")

    lines += [
        "",
        "## Renders (real report-worker-test; latency is this host, one replica)",
        "",
        "| Format | Success (non-hostile) | Success (hostile) | Hostile failures typed | "
        "Request -> rendered p50 / p95 (s) | DB created -> finished p50 / p95 (s) | "
        "Deterministic | Escapes |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for fmt in FORMATS:
        rs = [r for r in metric.renders if r.fmt == fmt]
        plain = [r for r in rs if not r.hostile]
        hostile = [r for r in rs if r.hostile]
        lat = [r.latency_s for r in rs if r.status == "succeeded" and r.latency_s is not None]
        db = [r.db_latency_s for r in rs if r.status == "succeeded" and r.db_latency_s is not None]
        twins = [r for r in rs if r.deterministic is not None]
        failed_hostile = [r for r in hostile if r.status != "succeeded"]
        lines.append(
            f"| {fmt} | {_rate(sum(r.status == 'succeeded' for r in plain), len(plain))} | "
            f"{_rate(sum(r.status == 'succeeded' for r in hostile), len(hostile))} | "
            f"{_rate(sum(r.typed for r in failed_hostile), len(failed_hostile))} | "
            f"{_secs(percentile(lat, 50))} / {_secs(percentile(lat, 95))} | "
            f"{_secs(percentile(db, 50))} / {_secs(percentile(db, 95))} | "
            f"{_rate(sum(bool(r.deterministic) for r in twins), len(twins))} | "
            f"{sum(len(r.escapes) for r in rs)} |"
        )
    fin = [v.finalize_s for v in finalized if v.finalize_s is not None]
    lines += [
        "",
        f"- Finalize wall time (snapshot build + redaction + sign + store), p50 / p95: "
        f"{_secs(percentile(fin, 50))} / {_secs(percentile(fin, 95))} s over {len(fin)} finalizes.",
        f"- Request -> rendered includes the broker, the sandboxed render, the upload and up to "
        f"{POLL_S} s of harness polling.",
        "- Peak render RSS: not measured here (the worker's `test_render_budget.py`).",
    ]

    by_category = Counter(e for r in metric.renders for e in r.escapes)
    hostile_visible = [r for r in metric.renders if r.payload_visible is not None]
    lines += [
        "",
        "## Hostile content",
        "",
        f"- Escapes by category: {dict(sorted(by_category.items())) or 'none'}.",
        f"- Positive control (hostile HTML / Markdown show the bidi payload as `⟨U+202E⟩`): "
        f"{_rate(sum(bool(r.payload_visible) for r in hostile_visible), len(hostile_visible))}.",
        "- Scanners are standard-library approximations (api-test has no markdown-it / pypdf); "
        "the authoritative parser checks are the worker suite (`test_render_md.py`, "
        "`test_render_html.py`, `test_render_pdf.py`).",
    ]
    if metric.refused_inputs:
        lines += ["", "Refused at input:", ""]
        lines += [f"- {item}" for item in metric.refused_inputs]

    lines += [
        "",
        "## Offline verification (scripts/verify_report.py)",
        "",
        "| Check | Expected | Result |",
        "| --- | --- | --- |",
    ]
    names = sorted({k for v in metric.versions for k in v.verify})
    for name in names:
        results = [v.verify[name] for v in metric.versions if name in v.verify]
        expected = "exit 1 (refused)" if name.startswith("tamper") else "exit 0"
        lines.append(f"| {name} | {expected} | {_rate(sum(results), len(results))} |")

    lines += [
        "",
        "## Per case",
        "",
        "| Case | Kind | Versions | Citations accurate | Renders ok | Deterministic | Escapes |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for plan in metric.plan:
        vs = [v for v in metric.versions if v.case == plan.index]
        rs = [r for r in metric.renders if r.case == plan.index]
        twins = [r for r in rs if r.deterministic is not None]
        lines.append(
            f"| {plan.index} | {plan.kind} | {len(vs)} | "
            f"{_rate(sum(v.accurate for v in vs), sum(v.citations for v in vs))} | "
            f"{sum(r.status == 'succeeded' for r in rs)}/{len(rs)} | "
            f"{sum(bool(r.deterministic) for r in twins)}/{len(twins)} | "
            f"{sum(len(r.escapes) for r in rs)} |"
        )
    if metric.case_errors:
        lines += ["", "Case errors:", ""]
        lines += [f"- {e}" for e in metric.case_errors]
    return "\n".join(lines)


