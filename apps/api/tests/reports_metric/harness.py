@dataclass(frozen=True)
class CasePlan:
    index: int
    kind: str  # dataset | hostile_rows | fixture_golden | fixture_hostile
    static: bool = False
    notes: int = 0
    collection_items: int = 0
    attack: bool = False
    ai_run: bool = False
    case_iocs: bool = False
    extra_rows: int = 0
    cited: int = 0

    @property
    def hostile(self) -> bool:
        return self.kind in ("hostile_rows", "fixture_hostile")

    @property
    def fixture(self) -> bool:
        return self.kind.startswith("fixture_")


def build_plan(cases: int = DEFAULT_CASES, seed: int = SEED) -> list[CasePlan]:
    """Two fixtures, n // 10 (at least one) hostile-row cases, the rest dataset cases."""
    if cases < 4:
        raise ValueError("the report metric needs at least 4 cases")
    rng = random.Random(f"{seed}:plan")  # noqa: S311 - a reproducible synthetic dataset
    plans = [CasePlan(0, "fixture_golden"), CasePlan(1, "fixture_hostile")]
    hostile_rows = max(1, cases // 10)
    for i in range(2, cases):
        hostile = i - 2 < hostile_rows
        plans.append(
            CasePlan(
                index=i,
                kind="hostile_rows" if hostile else "dataset",
                static=rng.random() < 0.3,
                notes=2 if hostile else rng.randint(0, 3),
                collection_items=3 if hostile else rng.choice((0, 0, 1, 3, 6)),
                attack=rng.random() < 0.5,
                ai_run=hostile or rng.random() < 0.35,
                case_iocs=hostile or rng.random() < 0.5,
                extra_rows=0 if hostile else rng.randint(0, 40),
                cited=rng.randint(1, 8),
            )
        )
    return plans


