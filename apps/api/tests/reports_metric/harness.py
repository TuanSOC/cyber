MAX_INFLATE = 64 * 1024 * 1024


class _Html(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.tags: list[tuple[str, list[tuple[str, str | None]], bool]] = []
        self.styles: list[str] = []
        self.comments = 0
        self.in_body = False
        self._cdata: str | None = None

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.tags.append((tag, attrs, self.in_body))
        if tag == "body":
            self.in_body = True
        if tag in ("style", "script"):
            self._cdata = tag

    def handle_endtag(self, tag: str) -> None:
        if tag == self._cdata:
            self._cdata = None

    def handle_data(self, data: str) -> None:
        if self._cdata == "style":
            self.styles.append(data)

    def handle_comment(self, data: str) -> None:
        self.comments += 1


def _href_ok(href: str, base_url: str | None) -> bool:
    if re.fullmatch(r"#[A-Za-z0-9_-]+", href):
        return True
    return base_url is not None and href.startswith(base_url.rstrip("/") + "/")


def html_escapes(data: bytes, base_url: str | None) -> list[str]:
    out: list[str] = []
    if not data.startswith(HTML_HEAD):
        out.append("html:head")
    text = data.decode("utf-8", errors="replace")
    parser = _Html()
    parser.feed(text)
    parser.close()
    styles = 0
    for tag, attrs, in_body in parser.tags:
        if tag not in HTML_TAGS:
            out.append(f"html:tag:{tag}")
        if tag == "style":
            styles += 1
            if in_body:
                out.append("html:style_in_body")
        if tag == "meta":
            equiv = dict(attrs).get("http-equiv")
            if equiv is not None and equiv.lower() != "content-security-policy":
                out.append("html:meta")
        for name, value in attrs:
            if name not in HTML_ATTRS:
                out.append(f"html:attr:{name}")
            elif name == "href" and not _href_ok(value or "", base_url):
                out.append("html:href")
    if styles > 1:
        out.append("html:extra_style")
    css = "".join(parser.styles).lower()
    out += [f"html:css:{needle}" for needle in CSS_FROM_DATA if needle in css]
    if parser.comments:
        out.append("html:comment")
    if BIDI.search(text):
        out.append("html:invisible")
    return out


def _md_closing(line: str, start: int, n: int) -> int:
    match = re.compile(rf"(?<!`)`{{{n}}}(?!`)").search(line, start)
    return match.start() if match else -1


def md_plain(line: str) -> str:
    """The line with code spans and backslash escapes replaced by placeholders: what is
    left is what a Markdown parser may interpret."""
    out: list[str] = []
    i = 0
    while i < len(line):
        ch = line[i]
        if ch == "\\" and i + 1 < len(line) and line[i + 1] in ASCII_PUNCTUATION:
            out.append("\x00")
            i += 2
            continue
        if ch == "`":
            j = i
            while j < len(line) and line[j] == "`":
                j += 1
            end = _md_closing(line, j, j - i)
            if end >= 0:
                out.append("\x01")
                i = end + (j - i)
                continue
            out.append(line[i:j])
            i = j
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def md_escapes(data: bytes, base_url: str | None) -> list[str]:
    out: list[str] = []
    text = data.decode("utf-8", errors="replace")
    if BIDI.search(text):
        out.append("md:invisible")
    for raw in text.splitlines():
        line = md_plain(raw.replace(base_url, "\x02") if base_url else raw)
        if "![" in line:
            out.append("md:image")
        for _label, target in _MD_LINK.findall(line):
            if not re.fullmatch(r"#c\d+", target):
                out.append("md:link")
        if _MD_REF.match(line):
            out.append("md:link_ref")
        if _MD_HTML.search(line):
            out.append("md:html")
        if _MD_ENTITY.search(line):
            out.append("md:entity")
        if _MD_SCHEME.search(line):
            out.append("md:autolink")
        if _MD_WWW.search(line):
            out.append("md:linkify_www")
        if _MD_EMAIL.search(line):
            out.append("md:linkify_email")
        if line.lstrip().startswith("|"):
            cells = line.strip().strip("|").split("|")
            if any(cell.strip()[:1] in ("=", "+", "@") for cell in cells if cell.strip()):
                out.append("md:formula")
    return out


def _pdf_name(raw: bytes) -> str:
    return _PDF_HEX.sub(lambda m: bytes([int(m.group(1), 16)]), raw).decode("latin-1")


def _pdf_text(raw: bytes) -> str:
    if raw.startswith(b"\xfe\xff"):
        return raw[2:].decode("utf-16-be", errors="replace")
    return raw.decode("latin-1")


def pdf_tokens(buf: bytes) -> tuple[list[str], list[str]]:
    """Names and `/URI` string values of PDF object syntax; strings are skipped as data."""
    names: list[str] = []
    uris: list[str] = []
    i, n = 0, len(buf)
    last: str | None = None
    while i < n:
        c = buf[i]
        if c == 0x28:  # literal string
            depth, j, value = 1, i + 1, bytearray()
            while j < n:
                ch = buf[j]
                if ch == 0x5C:
                    value += buf[j + 1 : j + 2]
                    j += 2
                    continue
                if ch == 0x28:
                    depth += 1
                elif ch == 0x29:
                    depth -= 1
                    if depth == 0:
                        j += 1
                        break
                value.append(ch)
                j += 1
            if last == "URI":
                uris.append(_pdf_text(bytes(value)))
            last, i = None, j
            continue
        if c == 0x3C and buf[i + 1 : i + 2] != b"<":  # hex string
            j = buf.find(b">", i + 1)
            j = n if j < 0 else j
            if last == "URI":
                digits = re.sub(rb"\s", b"", buf[i + 1 : j])
                digits += b"0" * (len(digits) % 2)
                try:
                    uris.append(_pdf_text(bytes.fromhex(digits.decode("ascii"))))
                except ValueError:
                    uris.append("<unreadable hex string>")
            last, i = None, j + 1
            continue
        if c == 0x2F:  # name
            match = _PDF_NAME.match(buf, i)
            assert match is not None
            name = _pdf_name(match.group(1))
            names.append(name)
            last, i = name, match.end()
            continue
        if c not in _PDF_WS:
            last = None
        i += 1
    return names, uris


def _pdf_syntax(pdf: bytes) -> Iterator[bytes]:
    """Object dictionaries, object-stream contents and the trailer (no file or page data)."""
    for match in _PDF_OBJ.finditer(pdf):
        body = match.group(2)
        stream = _PDF_STREAM.search(body)
        if stream is None:
            yield body
            continue
        head = body[: stream.start() + 2]
        yield head
        if re.search(rb"/Type\s*/ObjStm\b", head):
            raw = body[stream.end() :]
            if b"/FlateDecode" in head:
                try:
                    raw = zlib.decompressobj().decompress(raw, MAX_INFLATE)
                except zlib.error:
                    yield b"/MetricUnreadableObjStm"
                    continue
            yield raw
    at = pdf.rfind(b"trailer")
    if at >= 0:
        yield pdf[at : at + 4096]


def pdf_escapes(pdf: bytes, base_url: str | None) -> list[str]:
    out: list[str] = []
    for chunk in _pdf_syntax(pdf):
        names, uris = pdf_tokens(chunk)
        out += [f"pdf:name:{name}" for name in names if name in PDF_FORBIDDEN_NAMES]
        if "MetricUnreadableObjStm" in names:
            out.append("pdf:unreadable_object_stream")
        out += ["pdf:uri" for uri in uris if not _href_ok(uri, base_url)]
    return out


def scan(fmt: str, data: bytes, base_url: str | None) -> list[str]:
    if fmt == "html":
        return html_escapes(data, base_url)
    if fmt == "md":
        return md_escapes(data, base_url)
    return pdf_escapes(data, base_url)


def payload_visible(fmt: str, data: bytes) -> bool | None:
    """A positive control for hostile cases: the bidi payload reached the output as its
    visible `⟨U+202E⟩` form (HTML / Markdown only; PDF text is not extracted here)."""
    if fmt == "pdf":
        return None
    return "202E⟩" in data.decode("utf-8", errors="replace")


