"use client";

import { type ReactNode, useMemo } from "react";

import { type Integrity, IntegrityStrip } from "@/components/reports/integrity-strip";
import { CiteProvider, DataTable, Facts, openCitation } from "@/components/reports/report-parts";
import {
  AiSections,
  AlertsSection,
  AppendixSection,
  AssessmentSection,
  AttackSection,
  CaseSection,
  EvidenceSection,
  FindingsSection,
  IocsSection,
  JobsSection,
  NotesSection,
  TOC,
  TimelineSection,
} from "@/components/reports/report-sections";
import { RText } from "@/components/reports/report-text";
import { TlpBanner } from "@/components/reports/tlp-banner";
import { TlpBadge } from "@/components/tlp/tlp-badge";
import { formatUtc, shortSha } from "@/lib/report-format";
import { PROFILE_TEXT, type ReportSnapshot } from "@/lib/reports";

export const PREVIEW_WATERMARK = "PREVIEW, not finalized";

/**
 * The in-app report viewer: a signed version (`GET …/versions/{v}/content`) or a preview,
 * rendered from the snapshot JSON as React text, never from the renderer's HTML. TLP banners
 * top (sticky) and bottom, the cover facts and document control, the integrity strip, a table of
 * contents and every section in snapshot order, and the citation appendix.
 */
export function ReportView({
  orgId,
  snapshot,
  preview = false,
  integrity,
  onDownloadSignature,
  signaturePending,
  actions,
}: {
  orgId: string;
  snapshot: ReportSnapshot;
  preview?: boolean;
  integrity?: Integrity | null;
  onDownloadSignature?: () => void;
  signaturePending?: boolean;
  actions?: ReactNode;
}) {
  const known = useMemo(() => new Set(snapshot.citations.items.map((c) => c.cite_no)), [snapshot]);
  const report = snapshot.report;
  const headingId = preview ? "report-preview-title" : "report-title";

  return (
    <CiteProvider value={{ open: openCitation, known }}>
      <article aria-labelledby={headingId} className="relative" data-report-view={preview ? "preview" : "version"}>
        <TlpBanner tlp={report.tlp} position="top" sticky />
        {preview ? <PreviewWatermark /> : null}
        {preview ? (
          <p role="status" className="mt-3 rounded-md border-2 border-dashed border-amber-500 px-3 py-2 text-sm font-semibold">
            {PREVIEW_WATERMARK}: this is what version {report.version} would contain. It is not signed or stored.
          </p>
        ) : null}

        <header className="mt-6">
          <p className="text-xs tracking-wide text-muted-foreground uppercase">Incident report</p>
          <h1 id={headingId} tabIndex={-1} className="mt-1 text-2xl font-semibold tracking-tight outline-none">
            <RText value={report.title} />
          </h1>
          {actions ? <div className="mt-3 flex flex-wrap gap-2 print:hidden">{actions}</div> : null}
          <div className="mt-4">
            <Facts
              rows={[
                ["Case", <RText key="c" value={`${snapshot.case.case_ref} · ${snapshot.case.title}`} />],
                ["Version", preview ? `${report.version} (preview)` : String(report.version)],
                [preview ? "Built" : "Finalized", formatUtc(report.finalized_at)],
                ["Generated by", <RText key="g" value={report.generated_by} />],
                ["Profile", `${PROFILE_TEXT[report.profile]?.label ?? report.profile}`],
                ["Marking", <TlpBadge key="t" tlp={report.tlp} withDefinition />],
                ["Distribution", <RText key="d" value={report.distribution || "Not restricted beyond the marking."} />],
                ["Change note", <RText key="n" value={report.change_note} />],
                ["Report id", <RText key="i" value={report.report_id} mono />],
              ]}
            />
          </div>
          {integrity ? (
            <IntegrityStrip integrity={integrity} onDownloadSignature={onDownloadSignature} signaturePending={signaturePending} />
          ) : null}
          <div className="mt-6">
            <h2 className="mb-2 text-base font-semibold">Document control</h2>
            <DataTable
              caption="Document control: versions of this report"
              head={["Version", "Finalized", "SHA-256 (short)", "Change note"]}
              empty="First version."
              rows={[
                ...report.document_control.map((item) => [
                  `v${item.version}`,
                  formatUtc(item.finalized_at),
                  <RText key="s" value={item.snapshot_sha256_short} mono />,
                  <RText key="n" value={item.change_note} />,
                ]),
                [
                  `v${report.version}${preview ? " (preview)" : " (this version)"}`,
                  preview ? "not finalized" : formatUtc(report.finalized_at),
                  integrity ? <RText key="s" value={shortSha(integrity.sha256)} mono /> : "—",
                  <RText key="n" value={report.change_note} />,
                ],
              ]}
            />
          </div>
        </header>

        <nav aria-label="Contents" className="mt-8 rounded-md border p-3 print:hidden">
          <h2 className="mb-2 text-sm font-semibold">Contents</h2>
          <ol className="grid list-decimal gap-x-6 gap-y-0.5 pl-5 text-sm sm:grid-cols-2">
            {TOC.map((entry) => (
              <li key={entry.id}>
                <a href={`#${entry.id}`} className="underline-offset-4 hover:underline">
                  {entry.label}
                </a>
              </li>
            ))}
          </ol>
        </nav>

        <CaseSection snapshot={snapshot} />
        <AssessmentSection snapshot={snapshot} />
        <EvidenceSection snapshot={snapshot} />
        <JobsSection snapshot={snapshot} />
        <FindingsSection snapshot={snapshot} />
        <AlertsSection snapshot={snapshot} />
        <IocsSection snapshot={snapshot} />
        <AttackSection snapshot={snapshot} />
        <TimelineSection snapshot={snapshot} />
        <NotesSection snapshot={snapshot} />
        <AiSections snapshot={snapshot} />
        <AppendixSection orgId={orgId} snapshot={snapshot} />

        <div className="mt-10">
          <TlpBanner tlp={report.tlp} position="bottom" />
        </div>
      </article>
    </CiteProvider>
  );
}

function PreviewWatermark() {
  return (
    <div aria-hidden className="pointer-events-none absolute inset-0 z-10 flex flex-col justify-around overflow-hidden select-none">
      {[0, 1, 2, 3, 4, 5].map((n) => (
        <span
          key={n}
          className="block -rotate-12 text-center text-5xl font-black tracking-widest whitespace-nowrap text-amber-500/15 print:text-amber-500/25"
        >
          {PREVIEW_WATERMARK}
        </span>
      ))}
    </div>
  );
}
