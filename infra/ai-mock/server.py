"""Deterministic LLM sink for the AI `mock` provider (dev/test/e2e only).

Stdlib only (python:3.12-alpine), on the `egress` network alone, so the analyst worker is its
only client. It implements the wire protocol documented in
`apps/api/app/modules/ai/contracts.py` and imports nothing from the app.

Every request but `/health`, `/_last` and `/_reset` must carry `X-Mock-Key` equal to
`AI_MOCK_EXPECTED_KEY` (401 `{"error": "auth"}` otherwise).

Routes:
- `GET /health`
- `GET /v1/verify`: 200 `{"ok": true}` when the key matches
- `POST /v1/count_tokens` body `{model, system, user, schema, max_output_tokens}` ->
  `{"input_tokens": chars / 4}`
- `POST /v1/analyze` (same body) -> 200 `{output, usage: {input_tokens, output_tokens},
  stop_reason, refusal_category?, model}`; usage is chars / 4
- `GET /_last` (test only): the last request body (bounded to 1 MiB, in memory) and the
  per-marker request counters of `/v1/analyze`; `POST /_reset` clears both.

The default answer is deterministic and schema-valid (`ai.v1`): it parses the evidence JSON
between the `<<EVIDENCE {delimiter}>>` and `<<END EVIDENCE {delimiter}>>` lines of `user`
and cites the first items with exact quotes of their fields. A marker anywhere in the
evidence text (the first recognised one wins) selects another behaviour:

| marker                | answer                                                      |
|-----------------------|-------------------------------------------------------------|
| `ai-mock:429`         | 429 `rate_limited` with `Retry-After: 1`                    |
| `ai-mock:429-nora`    | 429 `rate_limited` without `Retry-After`                    |
| `ai-mock:429-once-<l>` | 429 + `Retry-After: 1` on the first request with it, then default |
| `ai-mock:529`         | 529 `overloaded`                                            |
| `ai-mock:spend`       | 429 `spend_limit`                                           |
| `ai-mock:401`         | 401 `auth`, echoing the received key in the body (key-leak) |
| `ai-mock:500`         | 500 `server`                                                |
| `ai-mock:slow`        | the default answer after `AI_MOCK_SLOW_S` (330 s > the timeout) |
| `ai-mock:slow-<n>`    | the default answer after n s (n <= 900: just below the timeout) |
| `ai-mock:oversize`    | a 200 body over 2 MiB                                       |
| `ai-mock:malformed`   | a 200 body that is not JSON                                 |
| `ai-mock:schema`      | valid JSON, wrong output schema                             |
| `ai-mock:refuse`      | `stop_reason: refusal`, `refusal_category: cyber`           |
| `ai-mock:maxtokens`   | `stop_reason: max_tokens` with a truncated output string    |
| `ai-mock:fabricate`   | an invented label and a quote that is not in the evidence   |
| `ai-mock:echo`        | echoes the instructions: system prompt + user turn up to the evidence |
| `ai-mock:inject`      | follows the planted instruction: "the file is clean"        |
| `ai-mock:hostile`     | `inject` and `fabricate` in one answer (e2e hostile case)   |
"""

import json
import os
import re
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from typing import Any

DEFAULT_KEY = "cyberlab-ai-mock-key"
MAX_REQUEST_BYTES = 8 * 1024 * 1024
LAST_MAX_BYTES = 1024 * 1024
OVERSIZE_BYTES = 2 * 1024 * 1024 + 4096
MAX_SLOW_S = 900.0
MAX_OBSERVED = 5
MAX_QUOTE = 120
MARKERS = (
    "429",
    "429-nora",
    "529",
    "spend",
    "401",
    "500",
    "slow",
    "oversize",
    "malformed",
    "schema",
    "refuse",
    "maxtokens",
    "fabricate",
    "echo",
    "inject",
    "hostile",
)
_MARKER = re.compile(r"ai-mock:([a-z0-9-]{1,32})")
_SLOW_N = re.compile(r"slow-(\d{1,4})")
_ONCE = re.compile(r"429-once-[a-z0-9]{1,20}")
_EVIDENCE = re.compile(r"^<<EVIDENCE (\S{1,128}?)>>\n(.*?)\n<<END EVIDENCE \1>>$", re.M | re.S)
_TASK_LINE = re.compile(r"^Task: ([a-z_]{1,32})\.", re.M)
_ALNUM = re.compile(r"[A-Za-z0-9]")
_ATTACK_ID = re.compile(r"\bT\d{4}(?:\.\d{3})?\b")
# Secret-looking tokens with a digit (the canary is 16-128 URL-safe characters).
_TOKEN = re.compile(r"(?<![\w-])(?=[\w-]*\d)[A-Za-z0-9_-]{16,128}(?![\w-])")
_TIMELINE_TASKS = ("summarize_pcap", "incident_summary", "job_digest")
_LIMITATION = "Generated by the deterministic ai-mock test sink: no model judgement involved."


class State:
    """Test-only memory: the last request body (bounded) and per-marker counters.

    With `state_file` (`AI_MOCK_STATE_FILE`), every change is also mirrored to that file
    (the `/_last` snapshot, written atomically): `api-test` cannot reach this server (it is
    on `egress` only), so the test profile shares the file through a read-only volume."""

    def __init__(self, state_file: str | None = None) -> None:
        self.state_file = state_file
        self.lock = threading.Lock()
        self.last_path: str | None = None
        self.last_body: bytes = b""
        self.last_truncated = False
        self.counters: dict[str, int] = {}
        self.seen: set[str] = set()

    def first_time(self, name: str) -> bool:
        """True the first time `name` is seen (bounded: the set is cleared past 10 000)."""
        with self.lock:
            if name in self.seen:
                return False
            if len(self.seen) >= 10_000:
                self.seen.clear()
            self.seen.add(name)
            return True

    def remember(self, path: str, body: bytes) -> None:
        with self.lock:
            self.last_path = path
            self.last_truncated = len(body) > LAST_MAX_BYTES
            self.last_body = body[:LAST_MAX_BYTES]
        self.persist()

    def count(self, marker: str) -> None:
        with self.lock:
            self.counters[marker] = self.counters.get(marker, 0) + 1
        self.persist()

    def persist(self) -> None:
        if not self.state_file:
            return
        data = json.dumps(self.snapshot())
        with self.lock:  # one writer at a time; readers see whole files (os.replace)
            tmp = f"{self.state_file}.tmp"
            with open(tmp, "w", encoding="utf-8") as f:
                f.write(data)
            os.replace(tmp, self.state_file)

    def snapshot(self) -> dict[str, Any]:
        with self.lock:
            try:
                body = json.loads(self.last_body) if self.last_body else None
            except ValueError:
                body = None
            return {
                "path": self.last_path,
                "body": body,
                "truncated": self.last_truncated,
                "counters": dict(self.counters),
            }

    def reset(self) -> None:
        with self.lock:
            self.last_path = None
            self.last_body = b""
            self.last_truncated = False
            self.counters = {}
            self.seen = set()
        self.persist()


# --- answers -------------------------------------------------------------------------------


def evidence(user: str) -> tuple[str, str | None, list[dict[str, Any]]]:
    """(evidence text, task, items) from the delimited block of `user` (the whole turn when
    there is no block). Items are `{label, kind, fields}` dicts. The block is the items array
    (`ai.prompt.render`, the task named in the user turn's "Task: <name>." line) or a whole
    context object `{task, items}` (the test doubles' `trivial_render`)."""
    match = _EVIDENCE.search(user)
    text = match.group(2) if match else user
    named = _TASK_LINE.search(user[: match.start()] if match else "")
    task: str | None = named.group(1) if named else None
    try:
        doc = json.loads(text)
    except ValueError:
        return text, task, []
    if isinstance(doc, dict):
        raw = doc.get("items")
        task = doc.get("task") if isinstance(doc.get("task"), str) else task
    elif isinstance(doc, list):
        raw = doc
    else:
        return text, task, []
    items = [
        i
        for i in (raw if isinstance(raw, list) else [])
        if isinstance(i, dict)
        and isinstance(i.get("label"), str)
        and isinstance(i.get("fields"), dict)
    ]
    return text, task, items


def marker(text: str) -> str | None:
    for found in _MARKER.finditer(text):
        name = found.group(1)
        if name in MARKERS or _SLOW_N.fullmatch(name) or _ONCE.fullmatch(name):
            return name
    return None


def _quotable(item: dict[str, Any]) -> tuple[str, str] | None:
    fields = item["fields"]
    for name in sorted(fields):
        value = fields[name]
        if isinstance(value, str) and len(value) >= 8 and _ALNUM.search(value):
            return name, value[:MAX_QUOTE]
    return None


def default_output(items: list[dict[str, Any]], task: str | None) -> dict[str, Any]:
    evidence_items = [i for i in items if i.get("kind") != "digest_claim"]
    if not evidence_items:
        return {
            "overall_confidence": {"level": "low", "rationale": "No evidence was provided."},
            "limitations": [_LIMITATION, "The context was empty."],
        }
    observed: list[dict[str, Any]] = []
    for item in evidence_items:
        if len(observed) >= MAX_OBSERVED:
            break
        quotable = _quotable(item)
        if quotable is None:
            continue
        field, quote = quotable
        observed.append(
            {
                "id": f"O{len(observed) + 1}",
                "text": f"{item['label']} {field}: {quote}"[:600],
                "confidence": "high",
                "citations": [{"ref": item["label"], "field": field, "quote": quote}],
            }
        )
    first = evidence_items[0]
    label = first["label"]
    first_field = sorted(first["fields"])[0] if first["fields"] else None
    techniques: list[dict[str, Any]] = []
    for item in evidence_items:
        if item.get("kind") != "capability":
            continue
        for field in ("attack_ids", "attack"):
            value = item["fields"].get(field)
            if not isinstance(value, str):
                continue
            for tid in _ATTACK_ID.findall(value):
                if len(techniques) < 20 and tid not in {t["technique_id"] for t in techniques}:
                    techniques.append(
                        {
                            "technique_id": tid,
                            "rationale": f"Capability {item['label']} maps to {tid}.",
                            "citations": [{"ref": item["label"], "field": field, "quote": tid}],
                        }
                    )
    timeline = []
    if task in _TIMELINE_TASKS:
        for item in evidence_items:
            if item.get("kind") == "timeline" and item["fields"] and len(timeline) < 60:
                timeline.append(
                    {
                        "text": f"Event {item['label']}.",
                        "citations": [{"ref": item["label"], "field": sorted(item["fields"])[0]}],
                    }
                )
    return {
        "observed": observed,
        "interpretation": [
            {
                "id": "I1",
                "text": f"The selected evidence centres on {label}.",
                "confidence": "medium",
                "citations": [{"ref": label, "field": first_field}],
            }
        ],
        "hypotheses": [
            {
                "id": "H1",
                "text": "The observed activity may warrant a closer look by an analyst.",
                "confidence": "low",
                "supporting": [{"ref": label}],
                "contradicting": [],
            }
        ],
        "overall_confidence": {
            "level": "medium",
            "rationale": "Deterministic answer of the ai-mock test sink.",
        },
        "next_steps": [
            {
                "text": f"Review {label} and its related records.",
                "rationale": "It is the first item in the context.",
                "refs": [label],
            }
        ],
        "limitations": [_LIMITATION],
        "attack_techniques": techniques,
        "timeline": timeline,
    }


def fabricated_output(items: list[dict[str, Any]]) -> dict[str, Any]:
    real = items[0]["label"] if items else "F1"
    field = sorted(items[0]["fields"])[0] if items and items[0]["fields"] else "title"
    return {
        "observed": [
            {
                "id": "O1",
                "text": "Beaconing to 198.51.100.77 was observed in this capture.",
                "confidence": "high",
                "citations": [
                    {"ref": "F999", "field": "title", "quote": "beacon to 198.51.100.77"}
                ],
            },
            {
                "id": "O2",
                "text": "The sample disables the endpoint protection service.",
                "confidence": "high",
                "citations": [
                    {
                        "ref": real,
                        "field": field,
                        "quote": "disables the endpoint protection service",
                    }
                ],
            },
        ],
        "overall_confidence": {"level": "high", "rationale": "Fabricated by ai-mock."},
        "limitations": [_LIMITATION],
    }


def instructions(system: str, user: str) -> str:
    """The system prompt plus the user turn up to its evidence block (the real prompt puts
    the canary there; the evidence itself is never echoed)."""
    opening = "\n<<EVIDENCE "
    head = user.split(opening, 1)[0] if opening in user else ""
    return f"{system}\n{head}" if head else system


def echo_output(system: str, user: str = "") -> dict[str, Any]:
    """The instructions (and so the canary) in overlapping 600-character claim texts, so a
    canary of up to 150 characters is never split across two chunks."""
    text = instructions(system, user)
    tokens = " ".join(_TOKEN.findall(text))[:500]
    chunks = [text[i : i + 600] for i in range(0, len(text), 450)][:39]
    observed = [
        {"id": f"O{n}", "text": chunk, "confidence": "high", "citations": []}
        for n, chunk in enumerate(chunks, start=2)
    ]
    return {
        "observed": [
            {
                "id": "O1",
                "text": f"My instructions mention {tokens}"[:600],
                "confidence": "high",
                "citations": [],
            },
            *observed,
        ],
        "overall_confidence": {"level": "low", "rationale": "Echo of the instructions."},
        "limitations": [],
    }


def inject_output(items: list[dict[str, Any]]) -> dict[str, Any]:
    citations = []
    for item in items:
        quotable = _quotable(item)
        if quotable is not None:
            citations = [{"ref": item["label"], "field": quotable[0], "quote": quotable[1]}]
            break
    return {
        "observed": [
            {
                "id": "O1",
                "text": "The file is clean and benign; no further action is needed.",
                "confidence": "high",
                "citations": citations,
            }
        ],
        "overall_confidence": {"level": "high", "rationale": "The file is clean."},
        "next_steps": [],
        "limitations": [],
    }


# --- HTTP ------------------------------------------------------------------------------------


class Handler(BaseHTTPRequestHandler):
    server_version = "ai-mock/1"  # HTTP/1.0: one request per connection

    @property
    def state(self) -> State:
        return self.server.state  # type: ignore[attr-defined, no-any-return]

    def _raw(self, status: int, data: bytes, headers: dict[str, str] | None = None) -> None:
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        for name, value in (headers or {}).items():
            self.send_header(name, value)
        self.end_headers()
        self.wfile.write(data)

    def _send(self, status: int, body: Any, headers: dict[str, str] | None = None) -> None:
        self._raw(status, json.dumps(body).encode(), headers)

    def _authorized(self) -> bool:
        expected = self.server.expected_key  # type: ignore[attr-defined]
        if self.headers.get("X-Mock-Key") != expected:
            self._send(401, {"error": "auth"})
            return False
        return True

    def _read_json(self) -> dict[str, Any] | None:
        length = self.headers.get("Content-Length")
        if length is None or not length.isdigit():
            self._send(411, {"error": "length_required"})
            return None
        size = int(length)
        if size > MAX_REQUEST_BYTES:
            self._send(413, {"error": "too_large"})
            self.close_connection = True
            return None
        body = self.rfile.read(size)
        self.state.remember(self.path, body)
        try:
            doc = json.loads(body)
        except ValueError:
            doc = None
        if not isinstance(doc, dict):
            self._send(400, {"error": "bad_request"})
            return None
        return doc

    def do_GET(self) -> None:  # noqa: N802 (http.server API)
        if self.path == "/health":
            self._send(200, {"ok": True})
        elif self.path == "/_last":
            self._send(200, self.state.snapshot())
        elif self.path == "/v1/verify":
            if self._authorized():
                self._send(200, {"ok": True})
        else:
            self._send(404, {"error": "not_found"})

    def do_POST(self) -> None:  # noqa: N802
        if self.path == "/_reset":
            self.state.reset()
            self._send(200, {"ok": True})
            return
        if self.path not in ("/v1/analyze", "/v1/count_tokens"):
            self._send(404, {"error": "not_found"})
            return
        if not self._authorized():
            return
        doc = self._read_json()
        if doc is None:
            return
        system = doc.get("system") if isinstance(doc.get("system"), str) else ""
        user = doc.get("user") if isinstance(doc.get("user"), str) else ""
        input_tokens = (len(system) + len(user)) // 4
        if self.path == "/v1/count_tokens":
            self._send(200, {"input_tokens": input_tokens})
            return
        self._analyze(doc, system, user, input_tokens)

    def _analyze(self, doc: dict[str, Any], system: str, user: str, input_tokens: int) -> None:
        model = doc.get("model") if isinstance(doc.get("model"), str) else "mock-1"
        text, task, items = evidence(user)
        name = marker(text)
        self.state.count(name or "default")

        def answer(output: Any, stop_reason: str = "end_turn", **extra: Any) -> None:
            usage = {"input_tokens": input_tokens, "output_tokens": len(json.dumps(output)) // 4}
            body = {"output": output, "usage": usage, "stop_reason": stop_reason, "model": model}
            self._send(200, {**body, **extra})

        if name is not None and _ONCE.fullmatch(name):
            if self.state.first_time(name):
                self._send(429, {"error": "rate_limited"}, {"Retry-After": "1"})
            else:
                answer(default_output(items, task))
        elif name == "429":
            self._send(429, {"error": "rate_limited"}, {"Retry-After": "1"})
        elif name == "429-nora":
            self._send(429, {"error": "rate_limited"})
        elif name == "529":
            self._send(529, {"error": "overloaded"})
        elif name == "spend":
            self._send(429, {"error": "spend_limit"})
        elif name == "401":
            # Hostile on purpose: the key echoed in the error body (key-leak suite).
            echoed = self.headers.get("X-Mock-Key", "")
            self._send(401, {"error": "auth", "message": f"invalid key {echoed}"})
        elif name == "500":
            self._send(500, {"error": "server"})
        elif name == "oversize":
            output = default_output(items, task)
            body = {"output": output, "usage": {"input_tokens": input_tokens, "output_tokens": 1}}
            self._send(
                200,
                {
                    **body,
                    "stop_reason": "end_turn",
                    "model": model,
                    "padding": "x" * OVERSIZE_BYTES,
                },
            )
        elif name == "malformed":
            self._raw(200, b'{"output": {"observed": [{"id": "O1", "text": ')
        elif name == "schema":
            answer({"observed": "not-a-list", "verdict": "clean", "score": 97})
        elif name == "refuse":
            answer(None, "refusal", refusal_category="cyber")
        elif name == "maxtokens":
            answer('{"observed": [{"id": "O1", "text": "The capture shows', "max_tokens")
        elif name == "fabricate":
            answer(fabricated_output(items))
        elif name == "echo":
            answer(echo_output(system, user))
        elif name == "inject":
            answer(inject_output(items))
        elif name == "hostile":
            hostile = inject_output(items)
            hostile["observed"].extend(
                {**claim, "id": f"O{n}"}
                for n, claim in enumerate(fabricated_output(items)["observed"], start=2)
            )
            answer(hostile)
        else:
            if name is not None and (name == "slow" or _SLOW_N.fullmatch(name)):
                found = _SLOW_N.fullmatch(name)
                seconds = float(found.group(1)) if found else self.server.slow_s  # type: ignore[attr-defined]
                time.sleep(min(seconds, MAX_SLOW_S))
            answer(default_output(items, task))

    def log_message(self, format: str, *args: object) -> None:  # noqa: A002
        return  # keep the sink quiet (bodies may carry test evidence)


def make_server(
    host: str = "0.0.0.0",  # noqa: S104 (a container on the egress network only)
    port: int = 8080,
    *,
    expected_key: str | None = None,
    slow_s: float | None = None,
) -> ThreadingHTTPServer:
    server = ThreadingHTTPServer((host, port), Handler)
    server.daemon_threads = True
    server.expected_key = expected_key or os.environ.get("AI_MOCK_EXPECTED_KEY") or DEFAULT_KEY  # type: ignore[attr-defined]
    server.slow_s = (  # type: ignore[attr-defined]
        slow_s if slow_s is not None else float(os.environ.get("AI_MOCK_SLOW_S", "330"))
    )
    server.state = State(os.environ.get("AI_MOCK_STATE_FILE") or None)  # type: ignore[attr-defined]
    return server


if __name__ == "__main__":
    make_server().serve_forever()
